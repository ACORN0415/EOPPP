import gcc
import os
import re
import copy

class EFlowGenerator:
    def __init__(self, output_dir="eflow_out"):
        self.output_dir = output_dir
        if not os.path.exists(self.output_dir):
            os.makedirs(self.output_dir)

        self.mif_depth = 16384
        self.buffer_z = {}
        self.buffer_y = {}
        self.buffer_cmt = {}

        self.cond_rhs_names = set()
        self.add_mode_vars = set()

        # SSA/ArrayRef semantic naming (to avoid raw ssa_1 names)
        self.ssa_semantic = {}   # ssa version(int) -> semantic name(str)
        self.name_alias = {}     # optional: raw name -> semantic name

    def generate(self, fun, init_gpc, op_gpc):
        # 0. SSA/ArrayRef 기반 semantic name 구축 (ssa_1 같은 임시명을 의미있는 이름으로 변환)
        self._build_semantic_names(fun)

        # 1. 분석 및 매핑 (강제 레지스터 할당 포함)
        reg_info = self._analyze_and_map_registers(fun)
        
        # 2. GPC 0 (초기화)
        init_state = self._generate_init_block(reg_info, init_gpc)
        
        # 3. GPC 1 (연산 - Fibo/FIR 로직 반영)
        self._generate_op_block(fun, reg_info, init_state, op_gpc)

    def write_all(self):
        path_z = os.path.join(self.output_dir, "total_program_z.mif")
        path_y = os.path.join(self.output_dir, "total_program_y.mif")

        header_comment = (
            "-- Generated by EFlowGenerator\n"
            "-- Z-bank: instruction/config word (Z[15:0] packed into low 16 bits of 32-bit word)\n"
            "-- Y-bank: data / ADD-path mask / loop control bits\n"
            "-- Loop control: y[127][31]=loopen_1d, y[127][15:0]=loop offset\n"
            "-- Format: [addr] : [DATA]; -- .rX [C-code] [Reg-combo] [Mnemonic] [Res] [GPC]\n"
        )

        self._write_mif_file(path_z, self.buffer_z, self.buffer_cmt, "Z-Bank (Instruction)", header_comment)
        self._write_mif_file(path_y, self.buffer_y, self.buffer_cmt, "Y-Bank (Data)", header_comment)
        print(f"\n[Success] Generated: {os.path.basename(path_z)} & {os.path.basename(path_y)}")

    def _safe_val(self, node):
        if node is None: return 0
        if isinstance(node, int): return node
        if isinstance(node, gcc.IntegerCst): return node.constant
        return 0

    
    # -------------------------------------------------------------------------
    # Semantic Naming Helpers (ArrayRef, SSA)
    # -------------------------------------------------------------------------
    def _arrayref_parts(self, node):
        """Return (base_name, index_int_or_None, index_name_str).
        Works for gcc.ArrayRef and compatible nodes.
        """
        if not isinstance(node, gcc.ArrayRef):
            return ("unknown", None, "0")

        base = getattr(node, 'array', None)
        if base is None:
            base = getattr(node, 'operand0', None)
        idx_node = getattr(node, 'index', None)
        if idx_node is None:
            idx_node = getattr(node, 'operand1', None)

        base_name = self._get_clean_name(base) if base is not None else "arr"
        # base_name may already have suffixes; keep only identifier part for naming
        base_name = str(base_name)

        idx_int = None
        if isinstance(idx_node, gcc.IntegerCst):
            idx_int = int(idx_node.constant)
        elif isinstance(idx_node, int):
            idx_int = int(idx_node)
        else:
            # Try to resolve constant-like nodes
            try:
                v = self._safe_val(idx_node)
                if isinstance(v, int):
                    idx_int = v
            except Exception:
                idx_int = None

        idx_name = self._get_clean_name(idx_node) if idx_node is not None else "0"
        return (base_name, idx_int, str(idx_name))

    def _semantic_name_for_arrayref(self, node):
        """Convert ArrayRef into stable semantic name.
        - If index is constant: base+index  (ex: xv[19] -> xv19)
        - Else: base[index] (kept as memref token; later filtered out from reg allocation)
        """
        base, idx_int, idx_name = self._arrayref_parts(node)
        # If base already ends with a digit (rare), keep bracket form to avoid ambiguity
        if idx_int is not None and not (len(base) > 0 and base[-1].isdigit()):
            return f"{base}{idx_int}"
        # Dynamic index: keep bracket form (treated as memory access)
        return f"{base}[{idx_name}]"

    def _build_semantic_names(self, fun):
        """Build ssa_semantic mapping so that _get_clean_name() returns meaningful names
        instead of ssa_1, ssa_2...
        Main rules:
          1) ssa <- ArrayRef  => semantic name from ArrayRef (xv19, h3, ...)
          2) ssa <- cast(ArrayRef) => same
          3) ssa <- MULT(hK, xvK) => tK (when K can be inferred)
        """
        self.ssa_semantic = {}
        # First pass: direct ArrayRef loads
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = stmt.lhs
                if not isinstance(lhs, gcc.SsaName):
                    continue
                ver = getattr(lhs, 'version', None)
                if ver is None:
                    continue

                # Case A: rhs is a single operand
                if len(stmt.rhs) == 1:
                    rhs0 = stmt.rhs[0]
                    # direct arrayref
                    if isinstance(rhs0, gcc.ArrayRef):
                        self.ssa_semantic[ver] = self._semantic_name_for_arrayref(rhs0)
                        continue
                    # cast/convert node containing operand1 which may be arrayref
                    op1 = getattr(rhs0, 'operand1', None)
                    if isinstance(op1, gcc.ArrayRef):
                        self.ssa_semantic[ver] = self._semantic_name_for_arrayref(op1)
                        continue

                # Case B: binary expr in stmt.rhs[0]
                if len(stmt.rhs) == 1 and hasattr(stmt.rhs[0], 'operand1') and hasattr(stmt.rhs[0], 'operand2'):
                    expr = stmt.rhs[0]
                    op_sym = self._get_op_symbol(getattr(expr, 'exprcode', stmt.exprcode))
                    if op_sym == '*':
                        # Try to infer tap index K from operands (xvK/hK or ArrayRef base+K)
                        n1 = self._get_clean_name(getattr(expr, 'operand1', None))
                        n2 = self._get_clean_name(getattr(expr, 'operand2', None))
                        k = None
                        for n in (n1, n2):
                            m = re.match(r'^(xv|h)(\d+)$', str(n))
                            if m:
                                k = int(m.group(2))
                                break
                        if k is not None:
                            self.ssa_semantic[ver] = f"t{k}"

        # Optional: second pass could propagate names through copies (ssaA = ssaB)
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = stmt.lhs
                if not isinstance(lhs, gcc.SsaName):
                    continue
                ver = getattr(lhs, 'version', None)
                if ver is None or ver in self.ssa_semantic:
                    continue
                if len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.SsaName):
                    src_ver = getattr(stmt.rhs[0], 'version', None)
                    if src_ver in self.ssa_semantic:
                        self.ssa_semantic[ver] = self.ssa_semantic[src_ver]

    def _get_clean_name(self, node):
        if node is None:
            return "0"
        if isinstance(node, int):
            return str(node)
        if isinstance(node, gcc.IntegerCst):
            return str(node.constant)

        # SSA name: prefer semantic name if we built one
        if isinstance(node, gcc.SsaName):
            ver = getattr(node, "version", None)
            if ver is not None and ver in self.ssa_semantic:
                return self.ssa_semantic[ver]
            var = getattr(node, "var", None)
            if var is not None:
                return self._get_clean_name(var)
            return f"ssa_{ver}" if ver is not None else "ssa"

        if isinstance(node, (gcc.VarDecl, gcc.ParmDecl)):
            nm = getattr(node, "name", None)
            return nm if nm else "var"

        # ArrayRef: base+index (xv19, h3, ...)
        if isinstance(node, gcc.ArrayRef):
            return self._semantic_name_for_arrayref(node)

        name = getattr(node, "name", None)
        return name if name else "unknown"

    def _get_op_symbol(self, exprcode):
        try:
            s = str(exprcode).lower()
            if "plus" in s: return "+"
            if "minus" in s: return "-"
            if "mult" in s: return "*" 
            if "ge" in s: return ">="
            if "le" in s: return "<="
            if "gt" in s: return ">"
            if "lt" in s: return "<"
            if "eq" in s: return "=="
            if "ne" in s: return "!="
        except: pass
        return "+"

    def _make_z16(self, opcode_hex,
                  mesh_right=False,
                  xd_mem=False,
                  y_left_xd=False,
                  sum_neg=False,
                  xx_left_xd=False,
                  write_en=False,
                  branch_hold=False,
                  a_bank_rd=False,
                  a_bank_wr=False,
                  a_addr_mode=0):
        """Return 16-bit Z field (zq_reg[15:0]).
        Field mapping:
          [4:0] opcode, [5] mesh, [6] XD source, [7] Y source,
          [8] SUM neg, [9] XX source, [10] write_en, [11] brgpc_hold,
          [12] A rd, [13] A wr, [15:14] A addr mode.
        """
        opcode = int(opcode_hex, 16) & 0x1F
        z = opcode
        if mesh_right: z |= (1 << 5)
        if xd_mem:     z |= (1 << 6)
        if y_left_xd:  z |= (1 << 7)
        if sum_neg:    z |= (1 << 8)
        if xx_left_xd: z |= (1 << 9)
        if write_en:   z |= (1 << 10)
        if branch_hold:z |= (1 << 11)
        if a_bank_rd:  z |= (1 << 12)
        if a_bank_wr:  z |= (1 << 13)
        z |= ((a_addr_mode & 0x3) << 14)
        return z & 0xFFFF

    def _z32_word(self, z16_int):
        """Pack 16-bit Z into a 32-bit MIF word (low 16 bits used)."""
        return f"{(z16_int & 0xFFFF):08x}"

    def _reg_idx(self, reg_str):
        if not reg_str or not isinstance(reg_str, str):
            return None
        if reg_str.startswith('r') and reg_str[1:].isdigit():
            return int(reg_str[1:])
        return None

    def _preferred_reg_index(self, clean_name):
        """Return preferred core/register index for semantic names like xv19, h3, t7.
        This is the 'forced register allocation' hook.
        Adjust offsets to match your floorplan.
        """
        s = str(clean_name)
        m = re.match(r'^(xv)(\d+)$', s)
        if m:
            return int(m.group(2))  # xv0 -> core0
        m = re.match(r'^(h)(\d+)$', s)
        if m:
            return 32 + int(m.group(2))  # h0 -> core32
        m = re.match(r'^(t)(\d+)$', s)
        if m:
            return 64 + int(m.group(2))  # t0 -> core64
        # Optional input stage naming: x0/x1...
        m = re.match(r'^(x)(\d+)$', s)
        if m:
            return 96 + int(m.group(2))  # x0 -> core96
        return None

    def _add_mask(self, dst_idx, src_indices):
        """Build ADD-mode Y mask using bit_index = 16 + (src - dst).
        Only supports |src-dst| <= 16.
        """
        mask = 0
        for src in src_indices:
            if src is None:
                continue
            delta = src - dst_idx
            bit = 16 + delta
            if 0 <= bit <= 31:
                mask |= (1 << bit)
        return mask & 0xFFFFFFFF

    # Backward compatible wrapper (returns 4-hex-digit Z[15:0])
    def _make_z_code_str(self, opcode_hex, write_en=False, branch_hold=False, pipeline_shift=False):
        z16 = self._make_z16(
            opcode_hex,
            write_en=write_en,
            branch_hold=branch_hold,
            xx_left_xd=pipeline_shift  # 기존 코드의 pipeline_shift는 bit[9]로 동작했음
        )
        return f"{z16:04x}"

    def _format_mnemonic(self, cmd_name, z_code_hex, y_val):
        try:
            y_int = int(y_val)
            y_hex = f"{y_int & 0xFFFFFFFF:08x}" # 8자리 16진수
        except:
            y_hex = "00000000"
        return f"{cmd_name}({z_code_hex}, {y_hex})"

    def _find_reg(self, clean_name, reg_map):
        if clean_name in reg_map: return reg_map[clean_name]["reg"]
        try:
            val = int(clean_name)
            if val == 0: return None
            if f"cst_{val}" in reg_map: return reg_map[f"cst_{val}"]["reg"]
            if f"cst_{abs(val)}" in reg_map: return reg_map[f"cst_{abs(val)}"]["reg"]
        except: pass
        return "r?"

    # -------------------------------------------------------------------------
    # 1. Analysis
    # -------------------------------------------------------------------------
    def _analyze_and_map_registers(self, fun):
        reg_map = {} 
        idx = 0
        self.cond_rhs_names = set()
        op_constants = set()
        self.add_mode_vars = set() 

        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleAssign):
                    lhs = self._get_clean_name(stmt.lhs)
                    self.add_mode_vars.add(lhs)
                    if len(stmt.rhs) >= 2:
                        for op in stmt.rhs:
                            self.add_mode_vars.add(self._get_clean_name(op))
                            if isinstance(op, gcc.IntegerCst):
                                op_constants.add(op.constant)
                                # SUB 미지원: a=b-const 형태는 (-const)도 상수로 준비
                                if self._get_op_symbol(stmt.exprcode) == '-':
                                    op_constants.add(-op.constant)
                    elif len(stmt.rhs) == 1:
                        rhs = stmt.rhs[0]
                        if hasattr(rhs, 'operand1'):
                            self.add_mode_vars.add(self._get_clean_name(rhs.operand1))
                            if isinstance(rhs.operand1, gcc.IntegerCst): op_constants.add(rhs.operand1.constant)
                            if hasattr(rhs, 'operand2') and rhs.operand2:
                                self.add_mode_vars.add(self._get_clean_name(rhs.operand2))
                                if isinstance(rhs.operand2, gcc.IntegerCst):
                                    op_constants.add(rhs.operand2.constant)
                                    if self._get_op_symbol(getattr(rhs, 'exprcode', stmt.exprcode)) == '-':
                                        op_constants.add(-rhs.operand2.constant)
                        else:
                            self.add_mode_vars.add(self._get_clean_name(rhs))

                elif isinstance(stmt, gcc.GimpleCond):
                    self.add_mode_vars.add(self._get_clean_name(stmt.lhs))
                    rhs_n = self._get_clean_name(stmt.rhs)
                    if rhs_n not in ("0", "unknown"):
                        self.cond_rhs_names.add(rhs_n)
                        self.add_mode_vars.add(rhs_n)
                    if isinstance(stmt.rhs, gcc.IntegerCst) and stmt.rhs.constant != 0:
                        op_constants.add(stmt.rhs.constant)

        sorted_vars = sorted([
            v for v in self.add_mode_vars
            if not v.lstrip('-').isdigit()
            and v != "unknown"
            and not v.startswith("cst_")
            # Dynamic ArrayRef (xn[i]) stays as memref token; don't allocate core regs for it
            and '[' not in v and ']' not in v
        ])

        taken = set()
        next_free = 0

        def alloc(name, preferred=None, vtype='var', val=0, disp_name=None):
            nonlocal next_free
            if preferred is not None and 0 <= preferred < 126 and preferred not in taken:
                idx_local = preferred
            else:
                while next_free in taken and next_free < 126:
                    next_free += 1
                idx_local = next_free
                next_free += 1
                if idx_local >= 126:
                    # reserve 126/127 for control; spill to r? (should be rejected by checker later)
                    idx_local = 125
            taken.add(idx_local)
            reg_map[name] = {
                'reg': f"r{idx_local}",
                'idx': idx_local,
                'val': val,
                'name': disp_name if disp_name is not None else name,
                'type': vtype
            }

        for name in sorted_vars:
            if name in reg_map:
                continue
            pref = self._preferred_reg_index(name)
            alloc(name, preferred=pref, vtype='var', val=0, disp_name=name)
        
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleAssign):
                    name = self._get_clean_name(stmt.lhs)
                    if name in reg_map and len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.IntegerCst):
                        raw = self._safe_val(stmt.rhs[0])
                        val = -raw if name in self.cond_rhs_names else raw
                        reg_map[name]['val'] = val

        for val in sorted(list(op_constants)):
            if val == 0:
                continue
            key = f"cst_{val}"
            if key in reg_map:
                continue
            # allocate constants after vars, no fixed preference
            final_val = -val if str(val) in self.cond_rhs_names else val
            # find next free core
            while next_free in taken and next_free < 126:
                next_free += 1
            if next_free >= 126:
                break
            taken.add(next_free)
            reg_map[key] = {
                'reg': f"r{next_free}",
                'idx': next_free,
                'val': final_val,
                'name': str(val),
                'type': 'const'
            }
            next_free += 1

        cond_count = 0
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleCond):
                    key = f"cond_res_{cond_count}"
                    if key in reg_map:
                        cond_count += 1
                        continue
                    while next_free in taken and next_free < 126:
                        next_free += 1
                    if next_free >= 126:
                        break
                    taken.add(next_free)
                    reg_map[key] = {
                        'reg': f"r{next_free}",
                        'idx': next_free,
                        'val': 4,
                        'name': "4 (outLoop)",
                        'type': 'cond'
                    }
                    next_free += 1
                    cond_count += 1
        return reg_map

    # -------------------------------------------------------------------------
    # 2. GPC 0 Init
    # -------------------------------------------------------------------------
    def _generate_init_block(self, reg_map, init_gpc):
        idx_to_info = {v['idx']: v for v in reg_map.values()}
        init_state = {}
        start_addr = init_gpc * 128

        # LXY: opcode 0x1F with write_en=1 (X-bank write)
        z16_lxy = self._make_z16("1f", write_en=True)
        z_word_lxy = self._z32_word(z16_lxy)
        z_code_hex = f"{z16_lxy:04x}"

        for i in range(128):
            addr = start_addr + i
            reg_name = f"r{i}"

            z_val, y_val = "00000000", "00000000"
            c_code, reg_comb, z_cmd, res_val = "", reg_name, "", "0"

            if i == 126:
                c_code = "return address"
            elif i == 127:
                c_code = "branch address"
            elif i in idx_to_info:
                info = idx_to_info[i]
                val = int(info['val'])
                c_code = f"{info['name']}={val}" if info['type'] == 'var' else f"{info['name']}"

                z_val = z_word_lxy
                y_val = f"{val & 0xFFFFFFFF:08x}"
                z_cmd = self._format_mnemonic("LXY", z_code_hex, val)
                res_val = str(val)

            self._add_line(addr, z_val, y_val, f".{reg_name}", c_code, reg_name, z_cmd, res_val, init_gpc)
            init_state[i] = {
                'z': z_val, 'y': y_val, 'core': f".{reg_name}",
                'c': c_code, 'rc': reg_name, 'cmd': z_cmd, 'res': res_val,
                'is_active': (i in idx_to_info)
            }
        return init_state

    def _generate_op_block(self, fun, reg_map, init_state, op_gpc):
        start_addr = op_gpc * 128
        current_state = copy.deepcopy(init_state)

        # ------------------------------------------------------------------
        # 0) 기본: Active register는 "자기 자신을 ADD해서 write-back"으로 유지
        #    (ADD 모드에서 self만 선택 -> Y mask bit16 = 1)
        # ------------------------------------------------------------------
        z16_keep = self._make_z16("00", write_en=True)
        z_keep = self._z32_word(z16_keep)
        z_keep_hex = f"{z16_keep:04x}"

        for i in range(128):
            if current_state[i]['is_active']:
                y_mask = self._add_mask(i, [i])  # self keep
                current_state[i].update({
                    'z': z_keep,
                    'y': f"{y_mask:08x}",
                    'cmd': self._format_mnemonic("ADD", z_keep_hex, y_mask),
                    'rc': f"r{i}",
                })
            else:
                current_state[i].update({'z': "00000000", 'y': "00000000", 'cmd': "", 'res': ""})

        # ------------------------------------------------------------------
        # 1) 계산 환경(주석용) + SSA 1-depth 전개용
        # ------------------------------------------------------------------
        env = {v['name']: v['val'] for v in reg_map.values()}
        for v in reg_map.values():
            env[f"cst_{v['name']}"] = v['val']

        ssa_defs = {}
        cond_count = 0

        def resolve_ssa_val(name, depth=0):
            if depth >= 1:
                return env.get(name, 0)
            if name in ssa_defs:
                d = ssa_defs[name]
                if d['op2'] is None:
                    return resolve_ssa_val(d['op1'], depth + 1)
                v1 = resolve_ssa_val(d['op1'], depth + 1)
                v2 = resolve_ssa_val(d['op2'], depth + 1)
                if d['sym'] == '+': return v1 + v2
                if d['sym'] == '-': return v1 - v2
                if d['sym'] == '*': return v1 * v2
            return env.get(name, 0)

        def resolve_ssa_str(name, depth=0):
            if depth >= 1:
                return name
            if name in ssa_defs:
                d = ssa_defs[name]
                if d['op2'] is None:
                    return resolve_ssa_str(d['op1'], depth + 1)
                s1 = resolve_ssa_str(d['op1'], depth + 1)
                s2 = resolve_ssa_str(d['op2'], depth + 1)
                return f"({s1}{d['sym']}{s2})"
            return name

        # 루프 컨트롤: y[127][31] (loopen_1d), y[127][15:0] (offset)
        loop_enable_1d = False
        loop_offset_1d = 0

        # ------------------------------------------------------------------
        # 2) BB 순회하며 연산/조건을 실제 eFlow word로 치환
        # ------------------------------------------------------------------
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                # ----------------------------------------------------------
                # (A) 대입문: ADD / SMT
                # ----------------------------------------------------------
                if isinstance(stmt, gcc.GimpleAssign):
                    lhs_name = self._get_clean_name(stmt.lhs)
                    if lhs_name not in reg_map:
                        continue

                    dst_idx = reg_map[lhs_name]['idx']
                    op1_nm, op2_nm, sym = None, None, "+"

                    # 형태1) rhs가 2개인 경우: a = b (+|-|*) c
                    if len(stmt.rhs) == 2:
                        op1_nm, op2_nm = self._get_clean_name(stmt.rhs[0]), self._get_clean_name(stmt.rhs[1])
                        sym = self._get_op_symbol(stmt.exprcode)

                    # 형태2) rhs가 1개인데 expr 노드로 operand1/2가 있는 경우
                    elif len(stmt.rhs) == 1:
                        rhs = stmt.rhs[0]
                        if isinstance(rhs, (gcc.SsaName, gcc.VarDecl, gcc.ParmDecl, gcc.IntegerCst, gcc.ArrayRef)):
                            op1_nm, op2_nm, sym = self._get_clean_name(rhs), None, ""
                        elif hasattr(rhs, 'operand1'):
                            op1_nm = self._get_clean_name(rhs.operand1)
                            op2_nm = self._get_clean_name(rhs.operand2) if getattr(rhs, 'operand2', None) is not None else None
                            sym = self._get_op_symbol(getattr(rhs, 'exprcode', stmt.exprcode))

                    if not op1_nm:
                        continue

                    # SSA 정의 기록 (주석용 depth=1 전개)
                    ssa_defs[lhs_name] = {'op1': op1_nm, 'op2': op2_nm, 'sym': sym}

                    # --- 레지스터 소스 추출 ---
                    r1 = self._find_reg(op1_nm, reg_map)
                    r2 = self._find_reg(op2_nm, reg_map) if op2_nm else None
                    src_indices = []

                    # helper: reg string -> idx
                    i1 = self._reg_idx(r1)
                    if i1 is not None:
                        src_indices.append(i1)

                    i2 = self._reg_idx(r2)
                    if i2 is not None:
                        src_indices.append(i2)

                    # --- 뺄셈: 상수만 음수화 후 ADD로 처리 (SUB 하드웨어 없음) ---
                    eff_sym = sym
                    eff_op2_nm = op2_nm
                    if sym == '-' and op2_nm:
                        try:
                            # op2가 즉시 상수면, -상수 레지스터를 사용하도록 문자열을 바꿈
                            eff_op2_nm = str(-int(op2_nm))
                            r2 = self._find_reg(eff_op2_nm, reg_map)
                            i2 = self._reg_idx(r2)
                            src_indices = [i1] if i1 is not None else []
                            if i2 is not None:
                                src_indices.append(i2)
                            eff_sym = '+'
                        except:
                            # 변수 뺄셈은 여기서 지원하지 않음 (추가 변환 필요)
                            eff_sym = sym

                    # --- SMT (비합산 모드) ---
                    if sym == '*':
                        z16 = self._make_z16("08", write_en=True)
                        z_word = self._z32_word(z16)
                        z_hex = f"{z16:04x}"

                        # 비합산 모드에서 Y는 2nd operand (즉시값/계수)
                        # - op2가 숫자 상수면 그대로 사용
                        # - op2가 hK 같은 '상수로 초기화된 변수'면 reg_map의 초기값을 사용
                        y_word = 0
                        if op2_nm is not None:
                            try:
                                y_word = int(str(op2_nm), 0)
                            except Exception:
                                if op2_nm in reg_map:
                                    y_word = int(reg_map[op2_nm].get('val', 0))
                                else:
                                    y_word = 0
                        # op2를 못 얻었는데 op1이 계수(hK)인 케이스도 지원
                        if y_word == 0 and op1_nm is not None and op1_nm in reg_map and str(op1_nm).startswith('h'):
                            y_word = int(reg_map[op1_nm].get('val', 0))

                        current_state[dst_idx].update({
                            'z': z_word,
                            'y': f"{y_word & 0xFFFFFFFF:08x}",
                            'c': f"{lhs_name}={op1_nm}*{op2_nm}",
                            'rc': f"{r1}*{r2 if r2 else op2_nm}",
                            'cmd': self._format_mnemonic("SMT", z_hex, y_word),
                            'res': str(resolve_ssa_val(lhs_name)),
                        })

                    # --- ADD (합산 모드) ---
                    else:
                        # ADD 모드에서 Y는 '합산 경로 마스크'
                        y_mask = self._add_mask(dst_idx, src_indices) if src_indices else self._add_mask(dst_idx, [dst_idx])

                        z16 = self._make_z16("00", write_en=True)
                        z_word = self._z32_word(z16)
                        z_hex = f"{z16:04x}"

                        # 주석 문자열
                        rc_str = f"{r1}" if r1 else op1_nm
                        c_str = f"{lhs_name}={op1_nm}"
                        if eff_op2_nm is not None:
                            rc2 = r2 if r2 else eff_op2_nm
                            rc_str = f"{rc_str}{eff_sym}{rc2}"
                            c_str = f"{c_str}{eff_sym}{eff_op2_nm}"

                        current_state[dst_idx].update({
                            'z': z_word,
                            'y': f"{y_mask:08x}",
                            'c': c_str,
                            'rc': rc_str,
                            'cmd': self._format_mnemonic("ADD", z_hex, y_mask),
                            'res': str(resolve_ssa_val(lhs_name)),
                        })

                # ----------------------------------------------------------
                # (B) 조건문: GTZ/GEZ/... (합산 모드 + BRGPC_HOLD)
                # ----------------------------------------------------------
                elif isinstance(stmt, gcc.GimpleCond):
                    lhs_nm = self._get_clean_name(stmt.lhs)
                    rhs_nm = self._get_clean_name(stmt.rhs)

                    exp_str = resolve_ssa_str(lhs_nm)
                    lhs_val = resolve_ssa_val(lhs_nm)
                    rhs_val = env.get(rhs_nm, 0)

                    op_raw = self._get_op_symbol(stmt.exprcode)

                    # 간단 heuristic: loop 조건은 i 관련 비교로 간주 -> exit 조건으로 뒤집기
                    is_loop_condition = (lhs_nm == 'i')
                    if is_loop_condition:
                        loop_enable_1d = True
                        logic_map = {"<": (">=", "GEZ", "06"),
                                     "<=": (">", "GTZ", "02"),
                                     ">": ("<=", "LEZ", "05"),
                                     ">=": ("<", "LTZ", "03"),
                                     "==": ("!=", "NEQZ", "04"),
                                     "!=": ("==", "EQZ", "01")}
                    else:
                        logic_map = {">": (">", "GTZ", "02"),
                                     ">=": (">=", "GEZ", "06"),
                                     "<": ("<", "LTZ", "03"),
                                     "<=": ("<=", "LEZ", "05"),
                                     "==": ("==", "EQZ", "01"),
                                     "!=": ("!=", "NEQZ", "04")}

                    logic_sym, cmd_name, opcode_hex = logic_map.get(op_raw, (">=", "GEZ", "06"))

                    # 조건문은 (lhs_expr + rhs) ? 0 형태로 만든다고 가정
                    final_res = lhs_val + rhs_val

                    # cond 결과 레지스터에 매핑(분기 플래그 생성용으로 사용)
                    cond_key = f"cond_res_{cond_count}"
                    if cond_key not in reg_map:
                        continue

                    dst_idx = reg_map[cond_key]['idx']

                    # lhs가 (a+b) 형태면 depth=1로 플랫하게 src 레지스터를 모으기
                    src_indices = []
                    if lhs_nm in ssa_defs and ssa_defs[lhs_nm]['op2'] is not None:
                        d = ssa_defs[lhs_nm]
                        src_indices.append(self._reg_idx(self._find_reg(d['op1'], reg_map)))
                        src_indices.append(self._reg_idx(self._find_reg(d['op2'], reg_map)))
                    else:
                        src_indices.append(self._reg_idx(self._find_reg(lhs_nm, reg_map)))

                    src_indices.append(self._reg_idx(self._find_reg(rhs_nm, reg_map)))
                    src_indices = [x for x in src_indices if x is not None]

                    y_mask = self._add_mask(dst_idx, src_indices) if src_indices else self._add_mask(dst_idx, [dst_idx])

                    z16 = self._make_z16(opcode_hex, branch_hold=True)
                    z_word = self._z32_word(z16)
                    z_hex = f"{z16:04x}"

                    full_c = f"{exp_str}+({rhs_nm}) {logic_sym} 0"
                    full_rc = f"{'+'.join([f'r{i}' for i in src_indices])} {logic_sym} 0 ? outL:inL" if src_indices else f"r{dst_idx} {logic_sym} 0 ? outL:inL"

                    current_state[dst_idx].update({
                        'z': z_word,
                        'y': f"{y_mask:08x}",
                        'c': full_c,
                        'rc': full_rc,
                        'cmd': self._format_mnemonic(cmd_name, z_hex, y_mask),
                        'res': str(final_res),
                    })
                    cond_count += 1

        # ------------------------------------------------------------------
        # 3) 루프 enable 비트는 Y[127][31]에 세팅 (loopen_1d)
        # ------------------------------------------------------------------
        if loop_enable_1d:
            y127 = (0x80000000 | (loop_offset_1d & 0xFFFF)) & 0xFFFFFFFF
            current_state[127]['y'] = f"{y127:08x}"
            # 루프 컨트롤은 합산 모드의 Y bits를 사용하므로, core127은 ADD 모드로 유지
            current_state[127]['z'] = self._z32_word(self._make_z16("00"))

        # ------------------------------------------------------------------
        # 4) 버퍼에 128줄 기록
        # ------------------------------------------------------------------
        for i in range(128):
            addr = start_addr + i
            st = current_state[i]
            self._add_line(addr, st['z'], st['y'], st['core'], st.get('c', ''), st.get('rc', ''), st.get('cmd', ''), st.get('res', ''), op_gpc)

    def _add_line(self, addr, z_val, y_val, core, c_code, reg_comb, cmd, res_val, gpc):
        self.buffer_z[addr] = z_val
        self.buffer_y[addr] = y_val
        self.buffer_cmt[addr] = f"{core:<6} {c_code:<30} {reg_comb:<30} {cmd:<20} {str(res_val):<8} GPC={gpc}"

    def _write_mif_file(self, path, data_dict, cmt_dict, desc, header):
        # 마지막으로 실제로 쓰인 주소까지 출력 (128 단위로 라운딩)
        max_addr = max(data_dict.keys()) if data_dict else -1
        if max_addr < 0:
            max_addr = 127
        end_addr = ((max_addr // 128) + 1) * 128 - 1

        with open(path, "w", encoding="utf-8") as f:
            # header는 '주석'만 포함하도록 write_all에서 전달
            if header:
                f.write(f"{header}\n")

            f.write(f"-- {desc}\n")
            f.write(f"DEPTH = {self.mif_depth};\n")
            f.write("WIDTH = 32;\n")
            f.write("ADDRESS_RADIX = DEC;\n")
            f.write("DATA_RADIX = HEX;\n")
            f.write("CONTENT\nBEGIN\n")

            for addr in range(end_addr + 1):
                if addr % 128 == 0:
                    f.write(f"\n-- -- GPC {addr // 128} --\n")
                val = data_dict.get(addr, "00000000")
                cmt = cmt_dict.get(addr, f".r{addr%128:<4} {'':<30} {'':<30} {'':<20} 0        GPC={addr//128}")
                f.write(f"{addr:<6} : {val}; -- {cmt}\n")
            f.write("END;\n")
