import gcc
import os
import re
import copy

class EFlowGenerator:
    """
    Generator rules (as agreed in chat):
      - Never emit raw ssa_# names in final mapping; try to alias SSA to meaningful names.
      - ArrayRef is always represented as base[index] (even if index is constant).
      - Dynamic index ArrayRef tokens are NOT excluded from core allocation.
      - Name prefix (e.g., xvK) is NOT used to decide algorithmic stage; only GIMPLE ops decide.
      - GPC even: init, GPC odd: op for that init (2 GPC per function).
      - Keep operation uses ADD self-mask, but comments must keep original variable meaning (not "keep").
      - Reg-combo column must not show raw literals as if they were registers; use [imm=..] when needed.
      - FIR "shift -> mult -> store(copy)" is expressed via stable reg allocation adjacency:
            xvK core, then tK core, then _K core (when present/derived).
    """

    def __init__(self, output_dir="eflow_out"):
        self.output_dir = output_dir
        os.makedirs(self.output_dir, exist_ok=True)

        self.mif_depth = 16384
        self.buffer_z = {}
        self.buffer_y = {}
        self.buffer_cmt = {}

        self.cond_rhs_names = set()
        self.add_mode_vars = []  # keep insertion order

        # SSA semantic naming
        self.ssa_semantic = {}   # ssa version(int) -> semantic name(str)

        # FIR tap constants captured from GIMPLE: h0=..., ...
        self.tap_values = {}     # "h0" -> int

    # -------------------------------------------------------------------------
    # Public API
    # -------------------------------------------------------------------------
    def generate(self, fun, init_gpc, op_gpc):
        # 0) Build SSA semantic names (avoid raw SSA temporary names)
        self._build_semantic_names(fun)

        # 1) Analyze and allocate cores (forced mapping with adjacency)
        reg_info = self._analyze_and_map_registers(fun)

        # 2) Even GPC: init
        init_state = self._generate_init_block(reg_info, init_gpc)

        # 3) Odd GPC: op
        self._generate_op_block(fun, reg_info, init_state, op_gpc)

        # Fixed: 2 GPC per function (even init, odd op)
        return 2

    def write_all(self):
        path_z = os.path.join(self.output_dir, "total_program_z.mif")
        path_y = os.path.join(self.output_dir, "total_program_y.mif")

        header_comment = (
            "-- Generated by EFlowGenerator\n"
            "-- Z-bank: instruction/config word (Z[15:0] packed into low 16 bits of 32-bit word)\n"
            "-- Y-bank: data / ADD-path mask / loop control bits\n"
            "-- Loop control: y[127][31]=loopen_1d, y[127][15:0]=loop offset\n"
            "-- Format: [addr] : [DATA]; -- .rX [C-code] [Reg-combo] [Mnemonic] [Res] [GPC]\n"
        )

        self._write_mif_file(path_z, self.buffer_z, self.buffer_cmt, "Z-Bank (Instruction)", header_comment)
        self._write_mif_file(path_y, self.buffer_y, self.buffer_cmt, "Y-Bank (Data)", header_comment)
        print(f"\n[Success] Generated: {os.path.basename(path_z)} & {os.path.basename(path_y)}")

    # -------------------------------------------------------------------------
    # Basic helpers
    # -------------------------------------------------------------------------
    def _safe_val(self, node):
        if node is None:
            return 0
        if isinstance(node, int):
            return node
        if isinstance(node, gcc.IntegerCst):
            return int(node.constant)
        return 0

    # -------------------------------------------------------------------------
    # Naming helpers (ArrayRef & SSA)
    # -------------------------------------------------------------------------
    def _arrayref_parts(self, node):
        """Return (base_node, index_node)."""
        base = getattr(node, 'array', None)
        if base is None:
            base = getattr(node, 'operand0', None)
        idx = getattr(node, 'index', None)
        if idx is None:
            idx = getattr(node, 'operand1', None)
        return base, idx

    def _name_for_arrayref(self, node):
        """ArrayRef is always represented as base[index] (even constant index)."""
        base, idx = self._arrayref_parts(node)
        base_name = self._get_clean_name(base) if base is not None else "arr"
        idx_name = self._get_clean_name(idx) if idx is not None else "0"
        return f"{base_name}[{idx_name}]"

    def _get_clean_name(self, node):
        if node is None:
            return "0"
        if isinstance(node, int):
            return str(node)
        if isinstance(node, gcc.IntegerCst):
            return str(int(node.constant))

        if isinstance(node, gcc.ArrayRef):
            return self._name_for_arrayref(node)

        # SSA name: use semantic mapping if present
        if isinstance(node, gcc.SsaName):
            ver = getattr(node, "version", None)
            if ver is not None and ver in self.ssa_semantic:
                return self.ssa_semantic[ver]

            var = getattr(node, "var", None)
            if var is not None:
                return self._get_clean_name(var)

            # Fallback: still avoid "ssa_#" per rule; use tmp<ver>
            return f"tmp{ver}" if ver is not None else "tmp"

        if isinstance(node, (gcc.VarDecl, gcc.ParmDecl)):
            nm = getattr(node, "name", None)
            return nm if nm else "var"

        nm = getattr(node, "name", None)
        return nm if nm else "unknown"

    def _get_op_symbol(self, exprcode):
        try:
            s = str(exprcode).lower()
            if "plus" in s:
                return "+"
            if "minus" in s:
                return "-"
            if "mult" in s:
                return "*"
            if "ge" in s:
                return ">="
            if "le" in s:
                return "<="
            if "gt" in s:
                return ">"
            if "lt" in s:
                return "<"
            if "eq" in s:
                return "=="
            if "ne" in s:
                return "!="
        except Exception:
            pass
        return "+"

    def _build_semantic_names(self, fun):
        """
        Build ssa_semantic so SSA temporaries are printable as meaningful names.
        Rules:
          - ssa <- ArrayRef               => base[index]
          - ssa <- cast(ArrayRef)         => base[index]
          - ssa <- (xvK * hK)             => tK (K inferred from operands' suffix digits)
          - ssa <- copy(tK)               => _K (store stage token)
          - ssa <- copy(X)                => X
        Note: ArrayRef constant index is NOT collapsed (xn[19] stays xn[19]).
        """
        self.ssa_semantic = {}
        self.tap_values = {}

        if not getattr(fun, "cfg", None):
            return

        # First: capture tap constants if present (h0=..., h1=...)
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = self._get_clean_name(stmt.lhs)
                if re.match(r"^h\d+$", lhs) and len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.IntegerCst):
                    self.tap_values[lhs] = int(stmt.rhs[0].constant)

        # Pass 1: direct ArrayRef / cast(ArrayRef) / copy propagation / mult naming
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = stmt.lhs
                if not isinstance(lhs, gcc.SsaName):
                    continue
                ver = getattr(lhs, "version", None)
                if ver is None:
                    continue

                # If rhs is a single operand
                if len(stmt.rhs) == 1:
                    rhs0 = stmt.rhs[0]

                    # direct arrayref
                    if isinstance(rhs0, gcc.ArrayRef):
                        self.ssa_semantic[ver] = self._name_for_arrayref(rhs0)
                        continue

                    # cast/convert node containing operand1 which may be arrayref
                    op1 = getattr(rhs0, "operand1", None)
                    if isinstance(op1, gcc.ArrayRef):
                        self.ssa_semantic[ver] = self._name_for_arrayref(op1)
                        continue

                    # simple copy
                    if isinstance(rhs0, (gcc.SsaName, gcc.VarDecl, gcc.ParmDecl)):
                        self.ssa_semantic[ver] = self._get_clean_name(rhs0)
                        continue

                # If rhs is an expr node with operand1/operand2
                expr = None
                if len(stmt.rhs) == 1 and hasattr(stmt.rhs[0], "operand1") and hasattr(stmt.rhs[0], "operand2"):
                    expr = stmt.rhs[0]
                elif len(stmt.rhs) == 2:
                    # Some gcc python bindings use rhs[0], rhs[1] directly for binary
                    expr = None

                if expr is not None:
                    sym = self._get_op_symbol(getattr(expr, "exprcode", stmt.exprcode))
                    op1n = self._get_clean_name(getattr(expr, "operand1", None))
                    op2n = self._get_clean_name(getattr(expr, "operand2", None))

                    if sym == "*":
                        # Try infer K from operands suffix digits in patterns: xvK, hK
                        k = None
                        for n in (op1n, op2n):
                            m = re.match(r"^(?:xv|h)(\d+)$", str(n))
                            if m:
                                k = int(m.group(1))
                                break
                        if k is not None:
                            self.ssa_semantic[ver] = f"t{k}"
                            continue

        # Pass 2: propagate copies and create _K for copy(tK)
        changed = True
        while changed:
            changed = False
            for bb in fun.cfg.basic_blocks:
                for stmt in bb.gimple:
                    if not isinstance(stmt, gcc.GimpleAssign):
                        continue
                    lhs = stmt.lhs
                    if not isinstance(lhs, gcc.SsaName):
                        continue
                    ver = getattr(lhs, "version", None)
                    if ver is None or ver in self.ssa_semantic:
                        continue
                    if len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.SsaName):
                        src_ver = getattr(stmt.rhs[0], "version", None)
                        if src_ver in self.ssa_semantic:
                            src_name = self.ssa_semantic[src_ver]
                            # If copying a tK, name it _K (store stage token)
                            m = re.match(r"^t(\d+)$", str(src_name))
                            if m:
                                self.ssa_semantic[ver] = f"_{m.group(1)}"
                            else:
                                self.ssa_semantic[ver] = src_name
                            changed = True

    # -------------------------------------------------------------------------
    # Z/Y helpers
    # -------------------------------------------------------------------------
    def _make_z16(self, opcode_hex,
                  mesh_right=False,
                  xd_mem=False,
                  y_left_xd=False,
                  sum_neg=False,
                  xx_left_xd=False,
                  write_en=False,
                  branch_hold=False,
                  a_bank_rd=False,
                  a_bank_wr=False,
                  a_addr_mode=0):
        """
        Return 16-bit Z field (zq_reg[15:0]).
        Field mapping:
          [4:0] opcode, [5] mesh, [6] XD source, [7] Y source,
          [8] SUM neg, [9] XX source, [10] write_en, [11] brgpc_hold,
          [12] A rd, [13] A wr, [15:14] A addr mode.
        """
        opcode = int(opcode_hex, 16) & 0x1F
        z = opcode
        if mesh_right:
            z |= (1 << 5)
        if xd_mem:
            z |= (1 << 6)
        if y_left_xd:
            z |= (1 << 7)
        if sum_neg:
            z |= (1 << 8)
        if xx_left_xd:
            z |= (1 << 9)
        if write_en:
            z |= (1 << 10)
        if branch_hold:
            z |= (1 << 11)
        if a_bank_rd:
            z |= (1 << 12)
        if a_bank_wr:
            z |= (1 << 13)
        z |= ((a_addr_mode & 0x3) << 14)
        return z & 0xFFFF

    def _z32_word(self, z16_int):
        return f"{(z16_int & 0xFFFF):08x}"

    def _reg_idx(self, reg_str):
        if not reg_str or not isinstance(reg_str, str):
            return None
        if reg_str.startswith("r") and reg_str[1:].isdigit():
            return int(reg_str[1:])
        return None

    def _add_mask(self, dst_idx, src_indices):
        """ADD-mode Y mask bit_index = 16 + (src - dst)."""
        mask = 0
        for src in src_indices:
            if src is None:
                continue
            delta = src - dst_idx
            bit = 16 + delta
            if 0 <= bit <= 31:
                mask |= (1 << bit)
        return mask & 0xFFFFFFFF

    def _format_mnemonic(self, cmd_name, z16_hex, y_val):
        try:
            y_int = int(y_val)
            y_hex = f"{y_int & 0xFFFFFFFF:08x}"
        except Exception:
            y_hex = "00000000"
        return f"{cmd_name}({z16_hex}, {y_hex})"

    # -------------------------------------------------------------------------
    # Register lookup/printing helpers
    # -------------------------------------------------------------------------
    def _find_reg(self, clean_name, reg_map):
        """Return register string like r4, or None (never 'r?')."""
        if clean_name is None:
            return None
        if clean_name in reg_map:
            return reg_map[clean_name]["reg"]

        # constant -> cst_<val>
        try:
            v = int(str(clean_name), 0)
            if v == 0:
                return None
            key = f"cst_{v}"
            if key in reg_map:
                return reg_map[key]["reg"]
        except Exception:
            pass
        return None

    # -------------------------------------------------------------------------
    # 1. Analysis & forced core allocation
    # -------------------------------------------------------------------------
    def _analyze_and_map_registers(self, fun):
        """
        - Collect vars in *appearance order* (not sorted), including ArrayRef tokens like xn[i].
        - Exclude hK from core allocation (fixed coefficients) but capture their constants.
        - Allocate cores with adjacency:
            xvK first (appearance order),
            then tK prefers xvK+1,
            then _K prefers tK+1.
        """
        reg_map = {}
        taken = set()
        next_free = 0

        self.cond_rhs_names = set()
        op_constants = set()
        names_seen = set()
        self.add_mode_vars = []

        def consider_name(nm):
            if nm in ("0", "unknown", None):
                return
            # exclude pure numbers from var list
            if str(nm).lstrip("-").isdigit():
                return
            # exclude hK from core allocation (coeffs handled as immediate)
            if re.match(r"^h\d+$", str(nm)):
                return
            if nm not in names_seen:
                names_seen.add(nm)
                self.add_mode_vars.append(nm)

        if not getattr(fun, "cfg", None):
            return reg_map

        # collect names + constants
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleAssign):
                    lhs = self._get_clean_name(stmt.lhs)
                    consider_name(lhs)

                    # collect RHS names and constants
                    for op in getattr(stmt, "rhs", []):
                        cn = self._get_clean_name(op)
                        consider_name(cn)
                        if isinstance(op, gcc.IntegerCst):
                            op_constants.add(int(op.constant))

                    # expr node inside rhs[0]
                    if len(stmt.rhs) == 1:
                        rhs0 = stmt.rhs[0]
                        op1 = getattr(rhs0, "operand1", None)
                        op2 = getattr(rhs0, "operand2", None)
                        if op1 is not None:
                            consider_name(self._get_clean_name(op1))
                            if isinstance(op1, gcc.IntegerCst):
                                op_constants.add(int(op1.constant))
                        if op2 is not None:
                            consider_name(self._get_clean_name(op2))
                            if isinstance(op2, gcc.IntegerCst):
                                op_constants.add(int(op2.constant))
                                if self._get_op_symbol(getattr(rhs0, "exprcode", stmt.exprcode)) == "-":
                                    op_constants.add(-int(op2.constant))

                elif isinstance(stmt, gcc.GimpleCond):
                    consider_name(self._get_clean_name(stmt.lhs))
                    rhs_n = self._get_clean_name(stmt.rhs)
                    consider_name(rhs_n)
                    if rhs_n not in ("0", "unknown"):
                        self.cond_rhs_names.add(rhs_n)
                    if isinstance(stmt.rhs, gcc.IntegerCst) and int(stmt.rhs.constant) != 0:
                        op_constants.add(int(stmt.rhs.constant))

        # Pass A: allocate base vars (not starting with t/_)
        base_vars = [n for n in self.add_mode_vars if not re.match(r"^(t|_)\d+$", str(n))]
        t_vars = [n for n in self.add_mode_vars if re.match(r"^t\d+$", str(n))]
        u_vars = [n for n in self.add_mode_vars if re.match(r"^_\d+$", str(n))]

        def alloc(name, preferred=None, vtype="var", val=0, disp_name=None):
            nonlocal next_free
            if name in reg_map:
                return

            idx_local = None
            if preferred is not None and 0 <= preferred < 126 and preferred not in taken:
                idx_local = preferred
            else:
                while next_free in taken and next_free < 126:
                    next_free += 1
                idx_local = min(next_free, 125)
                next_free = idx_local + 1

            taken.add(idx_local)
            reg_map[name] = {
                "reg": f"r{idx_local}",
                "idx": idx_local,
                "val": int(val),
                "name": disp_name if disp_name is not None else str(name),
                "type": vtype
            }

        for name in base_vars:
            alloc(name)

        # Pass B: allocate tK adjacent to xvK if possible
        for name in t_vars:
            m = re.match(r"^t(\d+)$", str(name))
            pref = None
            if m:
                k = m.group(1)
                xv = f"xv{k}"
                if xv in reg_map:
                    pref = reg_map[xv]["idx"] + 1
            alloc(name, preferred=pref)

        # Pass C: allocate _K adjacent to tK if possible, else xvK+2
        for name in u_vars:
            m = re.match(r"^_(\d+)$", str(name))
            pref = None
            if m:
                k = m.group(1)
                t = f"t{k}"
                xv = f"xv{k}"
                if t in reg_map:
                    pref = reg_map[t]["idx"] + 1
                elif xv in reg_map:
                    pref = reg_map[xv]["idx"] + 2
            alloc(name, preferred=pref)

        # Assign initial values from constant assignments (outside loop typically)
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = self._get_clean_name(stmt.lhs)
                if lhs in reg_map and len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.IntegerCst):
                    val = int(stmt.rhs[0].constant)
                    reg_map[lhs]["val"] = val

        # Allocate constants as cst_<val>
        for val in sorted(op_constants):
            if val == 0:
                continue
            key = f"cst_{val}"
            if key in reg_map:
                continue
            # reserve after vars
            alloc(key, vtype="const", val=val, disp_name=str(val))

        # Allocate condition result registers if needed
        cond_count = 0
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleCond):
                    key = f"cond_res_{cond_count}"
                    if key in reg_map:
                        cond_count += 1
                        continue
                    alloc(key, vtype="cond", val=0, disp_name="cond")
                    cond_count += 1

        return reg_map

    # -------------------------------------------------------------------------
    # 2. GPC even: Init block
    # -------------------------------------------------------------------------
    def _generate_init_block(self, reg_map, init_gpc):
        idx_to_info = {v["idx"]: v for v in reg_map.values()}
        init_state = {}
        start_addr = init_gpc * 128

        z16_lxy = self._make_z16("1f", write_en=True)
        z_word_lxy = self._z32_word(z16_lxy)
        z_hex = f"{z16_lxy:04x}"

        for i in range(128):
            addr = start_addr + i
            reg_name = f"r{i}"

            z_val, y_val = "00000000", "00000000"
            c_code, reg_comb, cmd, res_val = "", reg_name, "", ""

            if i == 126:
                c_code = "return address"
                res_val = ""
            elif i == 127:
                c_code = "branch address"
                res_val = ""
            elif i in idx_to_info:
                info = idx_to_info[i]
                val = int(info["val"])
                c_code = f"{info['name']}={val}" if info["type"] == "var" else f"{info['name']}"
                z_val = z_word_lxy
                y_val = f"{val & 0xFFFFFFFF:08x}"
                cmd = self._format_mnemonic("LXY", z_hex, val)
                res_val = str(val)

            self._add_line(addr, z_val, y_val, f".{reg_name}", c_code, reg_name, cmd, res_val, init_gpc)
            init_state[i] = {
                "z": z_val,
                "y": y_val,
                "core": f".{reg_name}",
                "c": c_code,
                "rc": reg_name,
                "cmd": cmd,
                "res": res_val,
                "is_active": (i in idx_to_info)
            }

        return init_state

    # -------------------------------------------------------------------------
    # 3. GPC odd: Op block
    # -------------------------------------------------------------------------
    def _generate_op_block(self, fun, reg_map, init_state, op_gpc):
        start_addr = op_gpc * 128
        current_state = copy.deepcopy(init_state)

        # Default: keep active registers via ADD self-mask
        z16_keep = self._make_z16("00", write_en=True)
        z_word_keep = self._z32_word(z16_keep)
        z_hex_keep = f"{z16_keep:04x}"

        for i in range(128):
            if current_state[i]["is_active"]:
                y_mask = self._add_mask(i, [i])
                current_state[i].update({
                    "z": z_word_keep,
                    "y": f"{y_mask:08x}",
                    "cmd": self._format_mnemonic("ADD", z_hex_keep, y_mask),
                    "rc": f"r{i}",
                    # NOTE: do NOT overwrite "c" (must keep init meaning; no 'keep')
                })
            else:
                current_state[i].update({"z": "00000000", "y": "00000000", "cmd": "", "res": ""})

        # Env for debug calc uses init values
        env = {v["name"]: v["val"] for v in reg_map.values()}
        for v in reg_map.values():
            env[f"cst_{v['name']}"] = v["val"]

        ssa_defs = {}
        cond_count = 0

        def resolve_ssa_val(name, depth=0):
            if depth >= 1:
                return env.get(name, 0)
            if name in ssa_defs:
                d = ssa_defs[name]
                if d["op2"] is None:
                    return resolve_ssa_val(d["op1"], depth + 1)
                v1 = resolve_ssa_val(d["op1"], depth + 1)
                v2 = resolve_ssa_val(d["op2"], depth + 1)
                if d["sym"] == "+":
                    return v1 + v2
                if d["sym"] == "-":
                    return v1 - v2
                if d["sym"] == "*":
                    return v1 * v2
            return env.get(name, 0)

        def resolve_ssa_str(name, depth=0):
            if depth >= 1:
                return name
            if name in ssa_defs:
                d = ssa_defs[name]
                if d["op2"] is None:
                    return resolve_ssa_str(d["op1"], depth + 1)
                s1 = resolve_ssa_str(d["op1"], depth + 1)
                s2 = resolve_ssa_str(d["op2"], depth + 1)
                return f"({s1}{d['sym']}{s2})"
            return name

        # Loop control bits (core127 Y)
        loop_enable_1d = False
        loop_offset_1d = 0

        # Traverse BBs and translate statements
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                # ---------------- Assign ----------------
                if isinstance(stmt, gcc.GimpleAssign):
                    lhs_name = self._get_clean_name(stmt.lhs)
                    if lhs_name not in reg_map:
                        continue

                    dst_idx = reg_map[lhs_name]["idx"]

                    # Parse RHS
                    op1_nm, op2_nm, sym = None, None, ""

                    if len(stmt.rhs) == 2:
                        op1_nm = self._get_clean_name(stmt.rhs[0])
                        op2_nm = self._get_clean_name(stmt.rhs[1])
                        sym = self._get_op_symbol(stmt.exprcode)

                    elif len(stmt.rhs) == 1:
                        rhs = stmt.rhs[0]
                        # Skip pure constant assignments in op (init already sets them)
                        if isinstance(rhs, gcc.IntegerCst):
                            continue

                        if isinstance(rhs, (gcc.SsaName, gcc.VarDecl, gcc.ParmDecl, gcc.ArrayRef)):
                            op1_nm, op2_nm, sym = self._get_clean_name(rhs), None, ""
                        elif hasattr(rhs, "operand1"):
                            op1_nm = self._get_clean_name(rhs.operand1)
                            op2_nm = self._get_clean_name(rhs.operand2) if getattr(rhs, "operand2", None) is not None else None
                            sym = self._get_op_symbol(getattr(rhs, "exprcode", stmt.exprcode))

                    if not op1_nm:
                        continue

                    # Record SSA definition (for debug)
                    ssa_defs[lhs_name] = {"op1": op1_nm, "op2": op2_nm, "sym": sym}

                    # Resolve registers for operands
                    r1 = self._find_reg(op1_nm, reg_map)
                    r2 = self._find_reg(op2_nm, reg_map) if op2_nm else None
                    i1 = self._reg_idx(r1)
                    i2 = self._reg_idx(r2)

                    # For RC display: never show raw literals as register; use [imm=]
                    def rc_of(op_nm, reg_str):
                        if reg_str:
                            return reg_str
                        # immediate?
                        try:
                            v = int(str(op_nm), 0)
                            return f"[imm={v}]"
                        except Exception:
                            return str(op_nm)

                    # Handle subtraction by constant via + (-const) if available
                    eff_sym = sym
                    eff_op2_nm = op2_nm
                    src_indices = []

                    if i1 is not None:
                        src_indices.append(i1)

                    if sym == "-" and op2_nm is not None:
                        try:
                            v2 = int(str(op2_nm), 0)
                            neg = -v2
                            eff_op2_nm = str(neg)
                            r2 = self._find_reg(eff_op2_nm, reg_map)
                            i2 = self._reg_idx(r2)
                            if i2 is not None:
                                src_indices.append(i2)
                            eff_sym = "+"
                        except Exception:
                            # variable-variable subtraction not handled here
                            if i2 is not None:
                                src_indices.append(i2)
                            eff_sym = "-"

                    else:
                        if i2 is not None:
                            src_indices.append(i2)

                    # --------------- SMT ---------------
                    if sym == "*":
                        z16 = self._make_z16("08", write_en=True)
                        z_word = self._z32_word(z16)
                        z_hex = f"{z16:04x}"

                        # Choose coefficient in Y:
                        # prefer hK fixed value; else numeric immediate; else reg_map init val.
                        y_word = 0
                        if op2_nm is not None:
                            if re.match(r"^h\d+$", str(op2_nm)) and str(op2_nm) in self.tap_values:
                                y_word = int(self.tap_values[str(op2_nm)])
                            else:
                                try:
                                    y_word = int(str(op2_nm), 0)
                                except Exception:
                                    if op2_nm in reg_map:
                                        y_word = int(reg_map[op2_nm].get("val", 0))
                        if y_word == 0 and op1_nm is not None and re.match(r"^h\d+$", str(op1_nm)) and str(op1_nm) in self.tap_values:
                            y_word = int(self.tap_values[str(op1_nm)])

                        current_state[dst_idx].update({
                            "z": z_word,
                            "y": f"{y_word & 0xFFFFFFFF:08x}",
                            "c": f"{lhs_name}={op1_nm}*{op2_nm}",
                            "rc": f"{rc_of(op1_nm, r1)}*{rc_of(op2_nm, r2)}",
                            "cmd": self._format_mnemonic("SMT", z_hex, y_word),
                            "res": str(resolve_ssa_val(lhs_name)),
                        })

                        # If lhs is tK, also generate store(copy) into _K (adjacent core)
                        mtk = re.match(r"^t(\d+)$", str(lhs_name))
                        if mtk:
                            k = mtk.group(1)
                            u_name = f"_{k}"
                            if u_name in reg_map:
                                u_idx = reg_map[u_name]["idx"]
                                # Copy from tK -> _K using ADD mask (source is dst_idx)
                                y_mask = self._add_mask(u_idx, [dst_idx])
                                z16c = self._make_z16("00", write_en=True)
                                z_wordc = self._z32_word(z16c)
                                z_hexc = f"{z16c:04x}"
                                current_state[u_idx].update({
                                    "z": z_wordc,
                                    "y": f"{y_mask:08x}",
                                    "c": f"{u_name}={lhs_name}",
                                    "rc": f"r{dst_idx}",
                                    "cmd": self._format_mnemonic("ADD", z_hexc, y_mask),
                                    "res": "",
                                })

                    # --------------- ADD / COPY ---------------
                    else:
                        if not src_indices:
                            src_indices = [dst_idx]
                        y_mask = self._add_mask(dst_idx, src_indices)

                        z16 = self._make_z16("00", write_en=True)
                        z_word = self._z32_word(z16)
                        z_hex = f"{z16:04x}"

                        rc_str = rc_of(op1_nm, r1)
                        c_str = f"{lhs_name}={op1_nm}"
                        if eff_op2_nm is not None:
                            rc2 = rc_of(eff_op2_nm, r2)
                            rc_str = f"{rc_str}{eff_sym}{rc2}"
                            c_str = f"{c_str}{eff_sym}{eff_op2_nm}"

                        current_state[dst_idx].update({
                            "z": z_word,
                            "y": f"{y_mask:08x}",
                            "c": c_str,
                            "rc": rc_str,
                            "cmd": self._format_mnemonic("ADD", z_hex, y_mask),
                            "res": str(resolve_ssa_val(lhs_name)),
                        })

                # ---------------- Cond ----------------
                elif isinstance(stmt, gcc.GimpleCond):
                    lhs_nm = self._get_clean_name(stmt.lhs)
                    rhs_nm = self._get_clean_name(stmt.rhs)

                    exp_str = resolve_ssa_str(lhs_nm)
                    lhs_val = resolve_ssa_val(lhs_nm)
                    rhs_val = env.get(rhs_nm, 0)

                    op_raw = self._get_op_symbol(stmt.exprcode)

                    # Heuristic: treat i-related compare as loop condition -> enable loop_1d
                    if lhs_nm == "i":
                        loop_enable_1d = True

                    logic_map = {
                        ">": ("GTZ", "02"),
                        ">=": ("GEZ", "06"),
                        "<": ("LTZ", "03"),
                        "<=": ("LEZ", "05"),
                        "==": ("EQZ", "01"),
                        "!=": ("NEQZ", "04"),
                    }
                    cmd_name, opcode_hex = logic_map.get(op_raw, ("GEZ", "06"))

                    cond_key = f"cond_res_{cond_count}"
                    if cond_key not in reg_map:
                        continue
                    dst_idx = reg_map[cond_key]["idx"]

                    # source indices: lhs (+ rhs) flattened one level if possible
                    src_indices = []
                    if lhs_nm in ssa_defs and ssa_defs[lhs_nm]["op2"] is not None:
                        d = ssa_defs[lhs_nm]
                        src_indices.append(self._reg_idx(self._find_reg(d["op1"], reg_map)))
                        src_indices.append(self._reg_idx(self._find_reg(d["op2"], reg_map)))
                    else:
                        src_indices.append(self._reg_idx(self._find_reg(lhs_nm, reg_map)))
                    src_indices.append(self._reg_idx(self._find_reg(rhs_nm, reg_map)))
                    src_indices = [x for x in src_indices if x is not None]

                    y_mask = self._add_mask(dst_idx, src_indices) if src_indices else self._add_mask(dst_idx, [dst_idx])

                    z16 = self._make_z16(opcode_hex, branch_hold=True)
                    z_word = self._z32_word(z16)
                    z_hex = f"{z16:04x}"

                    full_c = f"{exp_str}+({rhs_nm}) {op_raw} 0"
                    full_rc = "+".join([f"r{i}" for i in src_indices]) + f" {op_raw} 0 ? outL:inL"

                    current_state[dst_idx].update({
                        "z": z_word,
                        "y": f"{y_mask:08x}",
                        "c": full_c,
                        "rc": full_rc,
                        "cmd": self._format_mnemonic(cmd_name, z_hex, y_mask),
                        "res": str(lhs_val + rhs_val),
                    })
                    cond_count += 1

        # Apply loop control (core127 Y[31]=1, offset in [15:0])
        if loop_enable_1d:
            y127 = (0x80000000 | (loop_offset_1d & 0xFFFF)) & 0xFFFFFFFF
            current_state[127]["y"] = f"{y127:08x}"
            # Keep default ADD (or NOP) in Z; do not write loop in Z
            if current_state[127]["is_active"]:
                current_state[127]["z"] = z_word_keep
                current_state[127]["cmd"] = self._format_mnemonic("ADD", z_hex_keep, int(y127))
            else:
                current_state[127]["z"] = "00000000"
                current_state[127]["cmd"] = ""

        # Write 128 lines
        for i in range(128):
            addr = start_addr + i
            st = current_state[i]
            self._add_line(addr, st["z"], st["y"], st["core"], st.get("c", ""), st.get("rc", ""), st.get("cmd", ""), st.get("res", ""), op_gpc)

    # -------------------------------------------------------------------------
    # MIF buffering/writing
    # -------------------------------------------------------------------------
    def _add_line(self, addr, z_val, y_val, core, c_code, reg_comb, cmd, res_val, gpc):
        self.buffer_z[addr] = z_val
        self.buffer_y[addr] = y_val
        self.buffer_cmt[addr] = f"{core:<6} {c_code:<30} {reg_comb:<30} {cmd:<20} {str(res_val):<8} GPC={gpc}"

    def _write_mif_file(self, path, data_dict, cmt_dict, desc, header):
        max_addr = max(data_dict.keys()) if data_dict else -1
        if max_addr < 0:
            max_addr = 127
        end_addr = ((max_addr // 128) + 1) * 128 - 1

        with open(path, "w", encoding="utf-8") as f:
            if header:
                f.write(f"{header}\n")

            f.write(f"-- {desc}\n")
            f.write(f"DEPTH = {self.mif_depth};\n")
            f.write("WIDTH = 32;\n")
            f.write("ADDRESS_RADIX = DEC;\n")
            f.write("DATA_RADIX = HEX;\n")
            f.write("CONTENT\nBEGIN\n")

            for addr in range(end_addr + 1):
                if addr % 128 == 0:
                    f.write(f"\n-- -- GPC {addr // 128} --\n")
                val = data_dict.get(addr, "00000000")
                cmt = cmt_dict.get(addr, f".r{addr%128:<4} {'':<30} {'':<30} {'':<20} {'':<8} GPC={addr//128}")
                f.write(f"{addr:<6} : {val}; -- {cmt}\n")
            f.write("END;\n")
