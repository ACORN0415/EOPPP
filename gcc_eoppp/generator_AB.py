import gcc
import os
import re
import copy


class EFlowGenerator:
    """EFlow Generator

    목표:
    - (A) GIMPLE SSA 임시명(ssa_#)을 그대로 쓰지 않고, ArrayRef 인덱스를 파싱해
          xv19, t19 같은 의미 있는 이름을 만든 뒤 그 이름을 기반으로 코어/레지스터를 제어.
    - (B) FIR(13-tap)에서 SHIFT → STORE(copy) → MULT(SMT) → SUM/SRSH/STORE 순서로
          여러 GPC에 나눠 스케줄링.

    동작:
    - 일반 함수: 2 GPC (init, op)
    - FIR 함수: 1(init) + 4(op) = 5 GPC

    중요:
    - FIR tap h0~h12는 '고정 계수'로 보고 코어에 할당하지 않음(SMT Y-immediate로 사용)
    - xn[i], yo[i] 같은 동적 인덱스 ArrayRef는 코어 할당에서 제외(A-bank I/O로 처리)
    """

    def __init__(self, output_dir="eflow_out"):
        self.output_dir = output_dir
        os.makedirs(self.output_dir, exist_ok=True)

        self.mif_depth = 16384
        self.buffer_z = {}
        self.buffer_y = {}
        self.buffer_cmt = {}

        self.cond_rhs_names = set()
        self.add_mode_vars = set()

        # SSA/ArrayRef semantic naming
        self.ssa_semantic = {}  # ssa version(int) -> semantic name(str)

        # FIR coefficient cache: h0..h12 -> int
        self.fir_coeff = {}

    # ---------------------------------------------------------------------
    # Public API
    # ---------------------------------------------------------------------
    def generate(self, fun, init_gpc, op_gpc):
        """Generate blocks for a function.

        Returns: used_gpc_count (for main.py to advance gpc_counter)
        """
        # 0) Build semantic names first
        self._build_semantic_names(fun)

        # FIR mode? -> dedicated multi-GPC template
        if self._is_fir_function(fun):
            self.fir_coeff = self._extract_fir_coeffs(fun, taps=13)
            self._generate_fir_blocks(init_gpc, op_gpc)
            return 5

        # Generic mode
        reg_info = self._analyze_and_map_registers(fun)
        init_state = self._generate_init_block(reg_info, init_gpc)
        self._generate_op_block(fun, reg_info, init_state, op_gpc)
        return 2

    def write_all(self):
        path_z = os.path.join(self.output_dir, "total_program_z.mif")
        path_y = os.path.join(self.output_dir, "total_program_y.mif")

        header_comment = (
            "-- Generated by EFlowGenerator\n"
            "-- Z-bank: instruction/config word (Z[15:0] packed into low 16 bits of 32-bit word)\n"
            "-- Y-bank: data / ADD-path mask / loop control bits\n"
            "-- Loop control: y[127][31]=loopen_1d, y[127][15:0]=loop offset\n"
            "-- Format: [addr] : [DATA]; -- .rX [C-code] [Reg-combo] [Mnemonic] [Res] [GPC]\n"
        )

        self._write_mif_file(path_z, self.buffer_z, self.buffer_cmt, "Z-Bank (Instruction)", header_comment)
        self._write_mif_file(path_y, self.buffer_y, self.buffer_cmt, "Y-Bank (Data)", header_comment)
        print(f"\n[Success] Generated: {os.path.basename(path_z)} & {os.path.basename(path_y)}")

    # ---------------------------------------------------------------------
    # Basic helpers
    # ---------------------------------------------------------------------
    def _safe_val(self, node):
        if node is None:
            return 0
        if isinstance(node, int):
            return node
        if isinstance(node, gcc.IntegerCst):
            return node.constant
        return 0

    # ---------------------------------------------------------------------
    # Semantic naming (A)
    # ---------------------------------------------------------------------
    def _arrayref_parts(self, node):
        """Return (base_name, idx_int_or_None, idx_name_str)."""
        if not isinstance(node, gcc.ArrayRef):
            return ("unknown", None, "0")

        base = getattr(node, "array", None)
        if base is None:
            base = getattr(node, "operand0", None)
        idx_node = getattr(node, "index", None)
        if idx_node is None:
            idx_node = getattr(node, "operand1", None)

        base_name = self._get_clean_name(base) if base is not None else "arr"
        base_name = str(base_name)

        idx_int = None
        if isinstance(idx_node, gcc.IntegerCst):
            idx_int = int(idx_node.constant)
        elif isinstance(idx_node, int):
            idx_int = int(idx_node)
        else:
            # Try resolving constant-like
            try:
                v = self._safe_val(idx_node)
                if isinstance(v, int):
                    idx_int = v
            except Exception:
                idx_int = None

        idx_name = self._get_clean_name(idx_node) if idx_node is not None else "0"
        return (base_name, idx_int, str(idx_name))

    def _semantic_name_for_arrayref(self, node):
        """ArrayRef -> stable semantic name.

        - index가 상수면: base+index (xv[19] -> xv19)
        - index가 동적이면: base[idx] (xn[i] -> xn[i])  (메모리 토큰)
        """
        base, idx_int, idx_name = self._arrayref_parts(node)
        if idx_int is not None and not (len(base) > 0 and base[-1].isdigit()):
            # xv/h/t는 스칼라 레지스터로 취급
            if base in ("xv", "h", "t"):
                return f"{base}{idx_int}"
        return f"{base}[{idx_name}]"

    def _build_semantic_names(self, fun):
        """Build mapping: ssa-version -> semantic name."""
        self.ssa_semantic = {}

        if not getattr(fun, "cfg", None):
            return

        # Pass 1: ssa <- ArrayRef / cast(ArrayRef)
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = stmt.lhs
                if not isinstance(lhs, gcc.SsaName):
                    continue
                ver = getattr(lhs, "version", None)
                if ver is None:
                    continue

                if len(stmt.rhs) == 1:
                    rhs0 = stmt.rhs[0]
                    if isinstance(rhs0, gcc.ArrayRef):
                        self.ssa_semantic[ver] = self._semantic_name_for_arrayref(rhs0)
                        continue
                    op1 = getattr(rhs0, "operand1", None)
                    if isinstance(op1, gcc.ArrayRef):
                        self.ssa_semantic[ver] = self._semantic_name_for_arrayref(op1)
                        continue

                # binary expr wrapped in stmt.rhs[0]
                if len(stmt.rhs) == 1 and hasattr(stmt.rhs[0], "operand1") and hasattr(stmt.rhs[0], "operand2"):
                    expr = stmt.rhs[0]
                    op_sym = self._get_op_symbol(getattr(expr, "exprcode", stmt.exprcode))
                    if op_sym == "*":
                        n1 = self._get_clean_name(getattr(expr, "operand1", None))
                        n2 = self._get_clean_name(getattr(expr, "operand2", None))
                        k = None
                        for n in (n1, n2):
                            m = re.match(r"^(xv|h)(\d+)$", str(n))
                            if m:
                                k = int(m.group(2))
                                break
                        if k is not None:
                            self.ssa_semantic[ver] = f"t{k}"

        # Pass 2: propagate through copies (ssaA = ssaB)
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = stmt.lhs
                if not isinstance(lhs, gcc.SsaName):
                    continue
                ver = getattr(lhs, "version", None)
                if ver is None or ver in self.ssa_semantic:
                    continue
                if len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.SsaName):
                    src_ver = getattr(stmt.rhs[0], "version", None)
                    if src_ver in self.ssa_semantic:
                        self.ssa_semantic[ver] = self.ssa_semantic[src_ver]

    def _get_clean_name(self, node):
        if node is None:
            return "0"
        if isinstance(node, int):
            return str(node)
        if isinstance(node, gcc.IntegerCst):
            return str(node.constant)

        if isinstance(node, gcc.SsaName):
            ver = getattr(node, "version", None)
            if ver is not None and ver in self.ssa_semantic:
                return self.ssa_semantic[ver]
            var = getattr(node, "var", None)
            if var is not None:
                return self._get_clean_name(var)
            return f"ssa_{ver}" if ver is not None else "ssa"

        if isinstance(node, (gcc.VarDecl, gcc.ParmDecl)):
            nm = getattr(node, "name", None)
            return nm if nm else "var"

        if isinstance(node, gcc.ArrayRef):
            return self._semantic_name_for_arrayref(node)

        name = getattr(node, "name", None)
        return name if name else "unknown"

    def _get_op_symbol(self, exprcode):
        try:
            s = str(exprcode).lower()
            if "plus" in s:
                return "+"
            if "minus" in s:
                return "-"
            if "mult" in s:
                return "*"
            if "ge" in s:
                return ">="
            if "le" in s:
                return "<="
            if "gt" in s:
                return ">"
            if "lt" in s:
                return "<"
            if "eq" in s:
                return "=="
            if "ne" in s:
                return "!="
        except Exception:
            pass
        return "+"

    # ---------------------------------------------------------------------
    # Z/Y encoding
    # ---------------------------------------------------------------------
    def _make_z16(
        self,
        opcode_hex,
        mesh_right=False,
        xd_mem=False,
        y_left_xd=False,
        sum_neg=False,
        xx_left_xd=False,
        write_en=False,
        branch_hold=False,
        a_bank_rd=False,
        a_bank_wr=False,
        a_addr_mode=0,
    ):
        opcode = int(opcode_hex, 16) & 0x1F
        z = opcode
        if mesh_right:
            z |= (1 << 5)
        if xd_mem:
            z |= (1 << 6)
        if y_left_xd:
            z |= (1 << 7)
        if sum_neg:
            z |= (1 << 8)
        if xx_left_xd:
            z |= (1 << 9)
        if write_en:
            z |= (1 << 10)
        if branch_hold:
            z |= (1 << 11)
        if a_bank_rd:
            z |= (1 << 12)
        if a_bank_wr:
            z |= (1 << 13)
        z |= ((a_addr_mode & 0x3) << 14)
        return z & 0xFFFF

    def _z32_word(self, z16_int):
        return f"{(z16_int & 0xFFFF):08x}"

    def _format_mnemonic(self, cmd_name, z_code_hex, y_val):
        try:
            y_int = int(y_val)
            y_hex = f"{y_int & 0xFFFFFFFF:08x}"
        except Exception:
            y_hex = "00000000"
        return f"{cmd_name}({z_code_hex}, {y_hex})"

    # ---------------------------------------------------------------------
    # Register mapping & ADD mask
    # ---------------------------------------------------------------------
    def _reg_idx(self, reg_str):
        if not reg_str or not isinstance(reg_str, str):
            return None
        if reg_str.startswith("r") and reg_str[1:].isdigit():
            return int(reg_str[1:])
        return None

    def _preferred_reg_index(self, clean_name):
        """Forced register allocation hook.

        IMPORTANT (요구사항 반영):
        - FIR tap h#는 코어에 할당하지 않음 -> None
        - xv#/t#만 (원하는 경우) 선호 인덱스를 부여
        """
        s = str(clean_name)
        m = re.match(r"^(xv)(\d+)$", s)
        if m:
            # generic에서는 영향 최소화를 위해 선호만 제공 (실제 FIR은 별도 fixed mapping 사용)
            return int(m.group(2))
        m = re.match(r"^(t)(\d+)$", s)
        if m:
            return 64 + int(m.group(2))
        # h#는 고정 계수: 레지스터 할당 X
        if re.match(r"^h\d+$", s):
            return None
        return None

    def _add_mask(self, dst_idx, src_indices):
        """bit_index = 16 + (src - dst)"""
        mask = 0
        for src in src_indices:
            if src is None:
                continue
            delta = src - dst_idx
            bit = 16 + delta
            if 0 <= bit <= 31:
                mask |= (1 << bit)
        return mask & 0xFFFFFFFF

    def _find_reg(self, clean_name, reg_map):
        """Return "r#" or None.

        - unknown은 "r?"로 만들지 말고 None 반환 (r?가 mif에 퍼지는 문제 방지)
        - h#는 레지스터가 아니라 coeff dict로 처리 -> None
        """
        if clean_name is None:
            return None
        s = str(clean_name)
        if re.match(r"^h\d+$", s):
            return None
        if s in reg_map:
            return reg_map[s]["reg"]
        try:
            val = int(s)
            if val == 0:
                return None
            if f"cst_{val}" in reg_map:
                return reg_map[f"cst_{val}"]["reg"]
            if f"cst_{abs(val)}" in reg_map:
                return reg_map[f"cst_{abs(val)}"]["reg"]
        except Exception:
            pass
        return None

    # ---------------------------------------------------------------------
    # FIR detection & coeff extraction
    # ---------------------------------------------------------------------
    def _is_fir_function(self, fun):
        name = getattr(fun.decl, "name", "")
        if "fir" in name.lower():
            return True
        if not getattr(fun, "cfg", None):
            return False

        seen_xv0 = False
        seen_xv12 = False
        seen_yo = False
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleAssign):
                    lhs = self._get_clean_name(stmt.lhs)
                    if lhs == "xv0":
                        seen_xv0 = True
                    if lhs == "xv12":
                        seen_xv12 = True
                # yo[i] assignment is usually ArrayRef on LHS
                if isinstance(stmt, gcc.GimpleAssign) and isinstance(stmt.lhs, gcc.ArrayRef):
                    lhs = self._get_clean_name(stmt.lhs)
                    if lhs.startswith("yo["):
                        seen_yo = True
        return (seen_xv0 and seen_xv12 and seen_yo)

    def _extract_fir_coeffs(self, fun, taps=13):
        coeff = {f"h{k}": 0 for k in range(taps)}
        if not getattr(fun, "cfg", None):
            return coeff
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if not isinstance(stmt, gcc.GimpleAssign):
                    continue
                lhs = self._get_clean_name(stmt.lhs)
                if not re.match(r"^h\d+$", lhs):
                    continue
                if len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.IntegerCst):
                    coeff[lhs] = stmt.rhs[0].constant
        return coeff

    # ---------------------------------------------------------------------
    # 1. Analysis (generic)
    # ---------------------------------------------------------------------
    def _analyze_and_map_registers(self, fun):
        reg_map = {}
        self.cond_rhs_names = set()
        op_constants = set()
        self.add_mode_vars = set()

        if not getattr(fun, "cfg", None):
            return reg_map

        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleAssign):
                    lhs = self._get_clean_name(stmt.lhs)
                    self.add_mode_vars.add(lhs)

                    # rhs scanning
                    if len(stmt.rhs) >= 2:
                        for op in stmt.rhs:
                            nm = self._get_clean_name(op)
                            self.add_mode_vars.add(nm)
                            if isinstance(op, gcc.IntegerCst):
                                op_constants.add(op.constant)
                                # SUB 미지원 보완: a=b-const -> (-const)도 준비
                                if self._get_op_symbol(stmt.exprcode) == "-":
                                    op_constants.add(-op.constant)
                    elif len(stmt.rhs) == 1:
                        rhs = stmt.rhs[0]
                        if hasattr(rhs, "operand1"):
                            nm1 = self._get_clean_name(rhs.operand1)
                            self.add_mode_vars.add(nm1)
                            if isinstance(rhs.operand1, gcc.IntegerCst):
                                op_constants.add(rhs.operand1.constant)
                            if hasattr(rhs, "operand2") and rhs.operand2 is not None:
                                nm2 = self._get_clean_name(rhs.operand2)
                                self.add_mode_vars.add(nm2)
                                if isinstance(rhs.operand2, gcc.IntegerCst):
                                    op_constants.add(rhs.operand2.constant)
                                    if self._get_op_symbol(getattr(rhs, "exprcode", stmt.exprcode)) == "-":
                                        op_constants.add(-rhs.operand2.constant)
                        else:
                            self.add_mode_vars.add(self._get_clean_name(rhs))

                elif isinstance(stmt, gcc.GimpleCond):
                    lhs_nm = self._get_clean_name(stmt.lhs)
                    rhs_nm = self._get_clean_name(stmt.rhs)
                    self.add_mode_vars.add(lhs_nm)
                    if rhs_nm not in ("0", "unknown"):
                        self.cond_rhs_names.add(rhs_nm)
                        self.add_mode_vars.add(rhs_nm)
                    if isinstance(stmt.rhs, gcc.IntegerCst) and stmt.rhs.constant != 0:
                        op_constants.add(stmt.rhs.constant)

        # Filter vars: exclude digits-only, unknown, dynamic ArrayRef tokens, and h# taps
        sorted_vars = sorted(
            [
                v
                for v in self.add_mode_vars
                if not v.lstrip("-").isdigit()
                and v != "unknown"
                and "[" not in v
                and "]" not in v
                and not re.match(r"^h\d+$", v)  # taps are not core-allocated
            ]
        )

        taken = set()
        next_free = 0

        def alloc(name, preferred=None, vtype="var", val=0, disp_name=None):
            nonlocal next_free
            if preferred is not None and 0 <= preferred < 126 and preferred not in taken:
                idx_local = preferred
            else:
                while next_free in taken and next_free < 126:
                    next_free += 1
                idx_local = min(next_free, 125)
                next_free += 1
            taken.add(idx_local)
            reg_map[name] = {
                "reg": f"r{idx_local}",
                "idx": idx_local,
                "val": val,
                "name": disp_name if disp_name is not None else name,
                "type": vtype,
            }

        # Allocate vars
        for name in sorted_vars:
            if name in reg_map:
                continue
            pref = self._preferred_reg_index(name)
            alloc(name, preferred=pref, vtype="var", val=0, disp_name=name)

        # Initial values from direct constants
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleAssign):
                    name = self._get_clean_name(stmt.lhs)
                    if name in reg_map and len(stmt.rhs) == 1 and isinstance(stmt.rhs[0], gcc.IntegerCst):
                        raw = self._safe_val(stmt.rhs[0])
                        val = -raw if name in self.cond_rhs_names else raw
                        reg_map[name]["val"] = val

        # Allocate constants
        for val in sorted(list(op_constants)):
            if val == 0:
                continue
            key = f"cst_{val}"
            if key in reg_map:
                continue
            while next_free in taken and next_free < 126:
                next_free += 1
            if next_free >= 126:
                break
            taken.add(next_free)
            final_val = -val if str(val) in self.cond_rhs_names else val
            reg_map[key] = {
                "reg": f"r{next_free}",
                "idx": next_free,
                "val": final_val,
                "name": str(val),
                "type": "const",
            }
            next_free += 1

        # Allocate condition result regs
        cond_count = 0
        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                if isinstance(stmt, gcc.GimpleCond):
                    key = f"cond_res_{cond_count}"
                    while next_free in taken and next_free < 126:
                        next_free += 1
                    if next_free >= 126:
                        break
                    taken.add(next_free)
                    reg_map[key] = {
                        "reg": f"r{next_free}",
                        "idx": next_free,
                        "val": 4,
                        "name": "4 (outLoop)",
                        "type": "cond",
                    }
                    next_free += 1
                    cond_count += 1

        return reg_map

    # ---------------------------------------------------------------------
    # 2. GPC init (generic)
    # ---------------------------------------------------------------------
    def _generate_init_block(self, reg_map, init_gpc):
        idx_to_info = {v["idx"]: v for v in reg_map.values()}
        init_state = {}
        start_addr = init_gpc * 128

        z16_lxy = self._make_z16("1f", write_en=True)
        z_word_lxy = self._z32_word(z16_lxy)
        z_code_hex = f"{z16_lxy:04x}"

        for i in range(128):
            addr = start_addr + i
            reg_name = f"r{i}"

            z_val, y_val = "00000000", "00000000"
            c_code, reg_comb, z_cmd, res_val = "", reg_name, "", "0"

            if i == 126:
                c_code = "return address"
            elif i == 127:
                c_code = "branch address"
            elif i in idx_to_info:
                info = idx_to_info[i]
                val = int(info["val"])
                c_code = f"{info['name']}={val}" if info["type"] == "var" else f"{info['name']}"

                z_val = z_word_lxy
                y_val = f"{val & 0xFFFFFFFF:08x}"
                z_cmd = self._format_mnemonic("LXY", z_code_hex, val)
                res_val = str(val)

            self._add_line(addr, z_val, y_val, f".{reg_name}", c_code, reg_name, z_cmd, res_val, init_gpc)
            init_state[i] = {
                "z": z_val,
                "y": y_val,
                "core": f".{reg_name}",
                "c": c_code,
                "rc": reg_name,
                "cmd": z_cmd,
                "res": res_val,
                "is_active": (i in idx_to_info),
            }

        return init_state

    # ---------------------------------------------------------------------
    # 3. GPC op (generic)
    # ---------------------------------------------------------------------
    def _generate_op_block(self, fun, reg_map, init_state, op_gpc):
        start_addr = op_gpc * 128
        current_state = copy.deepcopy(init_state)

        # default keep: ADD self (mask bit16)
        z16_keep = self._make_z16("00", write_en=True)
        z_keep = self._z32_word(z16_keep)
        z_keep_hex = f"{z16_keep:04x}"

        for i in range(128):
            if current_state[i]["is_active"]:
                y_mask = self._add_mask(i, [i])
                current_state[i].update(
                    {
                        "z": z_keep,
                        "y": f"{y_mask:08x}",
                        "cmd": self._format_mnemonic("ADD", z_keep_hex, y_mask),
                        "rc": f"r{i}",
                    }
                )
            else:
                current_state[i].update({"z": "00000000", "y": "00000000", "cmd": "", "res": ""})

        # env: key by reg_map keys + numeric string for constants
        env = {}
        for key, info in reg_map.items():
            env[key] = info["val"]
            if info.get("type") == "const":
                env[str(info.get("name"))] = info["val"]

        ssa_defs = {}
        cond_count = 0

        def resolve_ssa_val(name, depth=0):
            if name is None:
                return 0
            if depth >= 1:
                return env.get(name, 0)
            if name in ssa_defs:
                d = ssa_defs[name]
                if d["op2"] is None:
                    return resolve_ssa_val(d["op1"], depth + 1)
                v1 = resolve_ssa_val(d["op1"], depth + 1)
                v2 = resolve_ssa_val(d["op2"], depth + 1)
                if d["sym"] == "+":
                    return v1 + v2
                if d["sym"] == "-":
                    return v1 - v2
                if d["sym"] == "*":
                    return v1 * v2
            return env.get(name, 0)

        def resolve_ssa_str(name, depth=0):
            if name is None:
                return "0"
            if depth >= 1:
                return name
            if name in ssa_defs:
                d = ssa_defs[name]
                if d["op2"] is None:
                    return resolve_ssa_str(d["op1"], depth + 1)
                s1 = resolve_ssa_str(d["op1"], depth + 1)
                s2 = resolve_ssa_str(d["op2"], depth + 1)
                return f"({s1}{d['sym']}{s2})"
            return name

        # loop control bits
        loop_enable_1d = False
        loop_offset_1d = 0

        if not getattr(fun, "cfg", None):
            return

        for bb in fun.cfg.basic_blocks:
            for stmt in bb.gimple:
                # ---------------- Assign ----------------
                if isinstance(stmt, gcc.GimpleAssign):
                    lhs_name = self._get_clean_name(stmt.lhs)
                    if lhs_name not in reg_map:
                        continue

                    dst_idx = reg_map[lhs_name]["idx"]
                    op1_nm, op2_nm, sym = None, None, "+"

                    if len(stmt.rhs) == 2:
                        op1_nm = self._get_clean_name(stmt.rhs[0])
                        op2_nm = self._get_clean_name(stmt.rhs[1])
                        sym = self._get_op_symbol(stmt.exprcode)
                    elif len(stmt.rhs) == 1:
                        rhs = stmt.rhs[0]
                        if isinstance(rhs, (gcc.SsaName, gcc.VarDecl, gcc.ParmDecl, gcc.IntegerCst, gcc.ArrayRef)):
                            op1_nm, op2_nm, sym = self._get_clean_name(rhs), None, ""
                        elif hasattr(rhs, "operand1"):
                            op1_nm = self._get_clean_name(rhs.operand1)
                            op2_nm = self._get_clean_name(rhs.operand2) if getattr(rhs, "operand2", None) is not None else None
                            sym = self._get_op_symbol(getattr(rhs, "exprcode", stmt.exprcode))

                    if not op1_nm:
                        continue

                    # record ssa defs for comment
                    ssa_defs[lhs_name] = {"op1": op1_nm, "op2": op2_nm, "sym": sym}

                    r1 = self._find_reg(op1_nm, reg_map)
                    r2 = self._find_reg(op2_nm, reg_map) if op2_nm else None

                    src_indices = []
                    i1 = self._reg_idx(r1)
                    if i1 is not None:
                        src_indices.append(i1)
                    i2 = self._reg_idx(r2)
                    if i2 is not None:
                        src_indices.append(i2)

                    # SUB: const only -> use (-const)
                    eff_sym = sym
                    eff_op2_nm = op2_nm
                    if sym == "-" and op2_nm:
                        try:
                            eff_op2_nm = str(-int(op2_nm))
                            r2 = self._find_reg(eff_op2_nm, reg_map)
                            i2 = self._reg_idx(r2)
                            src_indices = [i1] if i1 is not None else []
                            if i2 is not None:
                                src_indices.append(i2)
                            eff_sym = "+"
                        except Exception:
                            eff_sym = sym

                    # SMT
                    if sym == "*":
                        z16 = self._make_z16("08", write_en=True)
                        z_word = self._z32_word(z16)
                        z_hex = f"{z16:04x}"

                        # For generic: Y is second operand immediate if constant; else 0.
                        y_word = 0
                        if op2_nm is not None:
                            # if h# is used, try coeff dict
                            if re.match(r"^h\d+$", str(op2_nm)):
                                y_word = int(self.fir_coeff.get(str(op2_nm), 0))
                            else:
                                try:
                                    y_word = int(str(op2_nm), 0)
                                except Exception:
                                    if op2_nm in reg_map:
                                        y_word = int(reg_map[op2_nm].get("val", 0))
                        current_state[dst_idx].update(
                            {
                                "z": z_word,
                                "y": f"{y_word & 0xFFFFFFFF:08x}",
                                "c": f"{lhs_name}={op1_nm}*{op2_nm}",
                                "rc": f"{r1 if r1 else op1_nm}*{r2 if r2 else (op2_nm if op2_nm else '')}",
                                "cmd": self._format_mnemonic("SMT", z_hex, y_word),
                                "res": str(resolve_ssa_val(lhs_name)),
                            }
                        )

                    # ADD
                    else:
                        y_mask = self._add_mask(dst_idx, src_indices) if src_indices else self._add_mask(dst_idx, [dst_idx])
                        z16 = self._make_z16("00", write_en=True)
                        z_word = self._z32_word(z16)
                        z_hex = f"{z16:04x}"

                        rc_str = f"{r1}" if r1 else op1_nm
                        c_str = f"{lhs_name}={op1_nm}"
                        if eff_op2_nm is not None:
                            rc2 = r2 if r2 else eff_op2_nm
                            rc_str = f"{rc_str}{eff_sym}{rc2}"
                            c_str = f"{c_str}{eff_sym}{eff_op2_nm}"

                        current_state[dst_idx].update(
                            {
                                "z": z_word,
                                "y": f"{y_mask:08x}",
                                "c": c_str,
                                "rc": rc_str,
                                "cmd": self._format_mnemonic("ADD", z_hex, y_mask),
                                "res": str(resolve_ssa_val(lhs_name)),
                            }
                        )

                # ---------------- Cond ----------------
                elif isinstance(stmt, gcc.GimpleCond):
                    lhs_nm = self._get_clean_name(stmt.lhs)
                    rhs_nm = self._get_clean_name(stmt.rhs)

                    exp_str = resolve_ssa_str(lhs_nm)
                    lhs_val = resolve_ssa_val(lhs_nm)
                    rhs_val = env.get(rhs_nm, 0)

                    op_raw = self._get_op_symbol(stmt.exprcode)

                    is_loop_condition = (lhs_nm == "i")
                    if is_loop_condition:
                        loop_enable_1d = True
                        logic_map = {
                            "<": (">=", "GEZ", "06"),
                            "<=": (">", "GTZ", "02"),
                            ">": ("<=", "LEZ", "05"),
                            ">=": ("<", "LTZ", "03"),
                            "==": ("!=", "NEQZ", "04"),
                            "!=": ("==", "EQZ", "01"),
                        }
                    else:
                        logic_map = {
                            ">": (">", "GTZ", "02"),
                            ">=": (">=", "GEZ", "06"),
                            "<": ("<", "LTZ", "03"),
                            "<=": ("<=", "LEZ", "05"),
                            "==": ("==", "EQZ", "01"),
                            "!=": ("!=", "NEQZ", "04"),
                        }

                    logic_sym, cmd_name, opcode_hex = logic_map.get(op_raw, (">=", "GEZ", "06"))

                    final_res = lhs_val + rhs_val
                    cond_key = f"cond_res_{cond_count}"
                    if cond_key not in reg_map:
                        continue

                    dst_idx = reg_map[cond_key]["idx"]

                    src_indices = []
                    if lhs_nm in ssa_defs and ssa_defs[lhs_nm]["op2"] is not None:
                        d = ssa_defs[lhs_nm]
                        src_indices.append(self._reg_idx(self._find_reg(d["op1"], reg_map)))
                        src_indices.append(self._reg_idx(self._find_reg(d["op2"], reg_map)))
                    else:
                        src_indices.append(self._reg_idx(self._find_reg(lhs_nm, reg_map)))

                    src_indices.append(self._reg_idx(self._find_reg(rhs_nm, reg_map)))
                    src_indices = [x for x in src_indices if x is not None]

                    y_mask = self._add_mask(dst_idx, src_indices) if src_indices else self._add_mask(dst_idx, [dst_idx])

                    z16 = self._make_z16(opcode_hex, branch_hold=True)
                    z_word = self._z32_word(z16)
                    z_hex = f"{z16:04x}"

                    full_c = f"{exp_str}+({rhs_nm}) {logic_sym} 0"
                    full_rc = (
                        f"{'+'.join([f'r{i}' for i in src_indices])} {logic_sym} 0 ? outL:inL"
                        if src_indices
                        else f"r{dst_idx} {logic_sym} 0 ? outL:inL"
                    )

                    current_state[dst_idx].update(
                        {
                            "z": z_word,
                            "y": f"{y_mask:08x}",
                            "c": full_c,
                            "rc": full_rc,
                            "cmd": self._format_mnemonic(cmd_name, z_hex, y_mask),
                            "res": str(final_res),
                        }
                    )
                    cond_count += 1

        # loop enable bit -> Y[127][31]
        if loop_enable_1d:
            y127 = (0x80000000 | (loop_offset_1d & 0xFFFF)) & 0xFFFFFFFF
            current_state[127]["y"] = f"{y127:08x}"
            current_state[127]["z"] = self._z32_word(self._make_z16("00"))

        # commit 128 lines
        for i in range(128):
            addr = start_addr + i
            st = current_state[i]
            self._add_line(
                addr,
                st["z"],
                st["y"],
                st["core"],
                st.get("c", ""),
                st.get("rc", ""),
                st.get("cmd", ""),
                st.get("res", ""),
                op_gpc,
            )

    # ---------------------------------------------------------------------
    # FIR multi-GPC template (B)
    # ---------------------------------------------------------------------
    def _generate_fir_blocks(self, init_gpc, op_gpc):
        """Emit 5 GPCs for FIR.

        Mapping (fixed):
          core 0   : i
          core 1   : iT (optional)
          core 2   : one
          core 16..28 : xv0..xv12
          core 32..44 : t0..t12
          core 48  : acc
          core 49  : shr_out
          core 127 : loop control (Y[31]=1, offset)

        NOTE: loop termination(15회)까지 완전 구현하려면 BRGPC + target 설정이 필요.
              여기서는 기존 방식대로 loop_1d만 세팅(무한 반복)하고, 실험 시 오프셋만 보장.
        """
        taps = 13
        xv_cores = [16 + k for k in range(taps)]
        t_cores = [32 + k for k in range(taps)]

        core_i = 0
        core_iT = 1
        core_one = 2
        core_acc = 48
        core_shr = 49
        core_loop = 127

        def emit_gpc(gpc, entries):
            base = gpc * 128
            for core in range(128):
                addr = base + core
                if core in entries:
                    e = entries[core]
                    self._add_line(
                        addr,
                        e.get("z", "00000000"),
                        e.get("y", "00000000"),
                        f".r{core}",
                        e.get("c", ""),
                        e.get("rc", ""),
                        e.get("cmd", ""),
                        e.get("res", ""),
                        gpc,
                    )
                else:
                    self._add_line(addr, "00000000", "00000000", f".r{core}", "", "", "", "", gpc)

        def add_self_keep(core, note="keep"):
            z16 = self._make_z16("00", write_en=True)
            y = self._add_mask(core, [core])
            return {
                "z": self._z32_word(z16),
                "y": f"{y:08x}",
                "c": note,
                "rc": f"r{core}",
                "cmd": self._format_mnemonic("ADD", f"{z16:04x}", y),
                "res": "",
            }

        # ---------------- GPC init ----------------
        z16_lxy = self._make_z16("1f", write_en=True)
        z_lxy = self._z32_word(z16_lxy)
        z_lxy_hex = f"{z16_lxy:04x}"

        init_entries = {}

        init_entries[core_i] = {
            "z": z_lxy,
            "y": f"{0:08x}",
            "c": "i=0",
            "rc": "r0",
            "cmd": self._format_mnemonic("LXY", z_lxy_hex, 0),
            "res": "0",
        }
        init_entries[core_iT] = {
            "z": z_lxy,
            "y": f"{(-15) & 0xFFFFFFFF:08x}",
            "c": "iT=-15",
            "rc": "r1",
            "cmd": self._format_mnemonic("LXY", z_lxy_hex, -15),
            "res": "-15",
        }
        init_entries[core_one] = {
            "z": z_lxy,
            "y": f"{1:08x}",
            "c": "one=1",
            "rc": "r2",
            "cmd": self._format_mnemonic("LXY", z_lxy_hex, 1),
            "res": "1",
        }

        for k, c in enumerate(xv_cores):
            init_entries[c] = {
                "z": z_lxy,
                "y": f"{0:08x}",
                "c": f"xv{k}=0",
                "rc": f"r{c}",
                "cmd": self._format_mnemonic("LXY", z_lxy_hex, 0),
                "res": "0",
            }

        # acc/shr init 0
        init_entries[core_acc] = {
            "z": z_lxy,
            "y": f"{0:08x}",
            "c": "acc=0",
            "rc": f"r{core_acc}",
            "cmd": self._format_mnemonic("LXY", z_lxy_hex, 0),
            "res": "0",
        }
        init_entries[core_shr] = {
            "z": z_lxy,
            "y": f"{0:08x}",
            "c": "shr=0",
            "rc": f"r{core_shr}",
            "cmd": self._format_mnemonic("LXY", z_lxy_hex, 0),
            "res": "0",
        }

        # loopctl init
        init_entries[core_loop] = {"z": "00000000", "y": "00000000", "c": "loopctl init", "rc": "", "cmd": "", "res": ""}

        emit_gpc(init_gpc, init_entries)

        # ---------------- op+0: SHIFT + LOAD ----------------
        g0 = op_gpc + 0
        e0 = {}
        # keep everything we care about
        for core in [core_i, core_iT, core_one, core_acc, core_shr, core_loop] + xv_cores + t_cores:
            e0[core] = add_self_keep(core)

        # i = i + 1
        z16_add = self._make_z16("00", write_en=True)
        m_i = self._add_mask(core_i, [core_i, core_one])
        e0[core_i] = {
            "z": self._z32_word(z16_add),
            "y": f"{m_i:08x}",
            "c": "i=i+1",
            "rc": "r0+r2",
            "cmd": self._format_mnemonic("ADD", f"{z16_add:04x}", m_i),
            "res": "",
        }

        # shift xv12<-xv11 ... xv1<-xv0
        for k in range(taps - 1, 0, -1):
            dst = xv_cores[k]
            src = xv_cores[k - 1]
            m = self._add_mask(dst, [src])
            e0[dst] = {
                "z": self._z32_word(z16_add),
                "y": f"{m:08x}",
                "c": f"xv{k}=xv{k-1} (shift)",
                "rc": f"r{src}",
                "cmd": self._format_mnemonic("ADD", f"{z16_add:04x}", m),
                "res": "",
            }

        # xv0 = xn[i] : A_BANK_RD (+ addr inc)
        # NOTE: 주소 발생기는 외부 설정/가정이 필요. 여기서는 a_addr_mode=1(inc)로 표기.
        z16_ld = self._make_z16("00", write_en=True, a_bank_rd=True, a_addr_mode=1)
        m0 = self._add_mask(xv_cores[0], [xv_cores[0]])
        e0[xv_cores[0]] = {
            "z": self._z32_word(z16_ld),
            "y": f"{m0:08x}",
            "c": "xv0=xn[i] (A_RD)",
            "rc": "A[xn++]",
            "cmd": self._format_mnemonic("ADD|A_RD", f"{z16_ld:04x}", m0),
            "res": "",
        }

        emit_gpc(g0, e0)

        # ---------------- op+1: STORE(copy) xv -> t ----------------
        g1 = op_gpc + 1
        e1 = {}
        for core in [core_i, core_iT, core_one, core_acc, core_shr, core_loop] + xv_cores + t_cores:
            e1[core] = add_self_keep(core)

        for k in range(taps):
            dst = t_cores[k]
            src = xv_cores[k]
            m = self._add_mask(dst, [src])
            e1[dst] = {
                "z": self._z32_word(z16_add),
                "y": f"{m:08x}",
                "c": f"t{k}=xv{k} (copy)",
                "rc": f"r{src}",
                "cmd": self._format_mnemonic("ADD", f"{z16_add:04x}", m),
                "res": "",
            }

        emit_gpc(g1, e1)

        # ---------------- op+2: MULT SMT (t * h) ----------------
        g2 = op_gpc + 2
        e2 = {}
        for core in [core_i, core_iT, core_one, core_acc, core_shr, core_loop] + xv_cores + t_cores:
            e2[core] = add_self_keep(core)

        for k in range(taps):
            dst = t_cores[k]
            hk = int(self.fir_coeff.get(f"h{k}", 0))
            z16_smt = self._make_z16("08", write_en=True)
            e2[dst] = {
                "z": self._z32_word(z16_smt),
                "y": f"{hk & 0xFFFFFFFF:08x}",
                "c": f"t{k}=t{k}*h{k}",
                "rc": f"r{dst}*h{k}",
                "cmd": self._format_mnemonic("SMT", f"{z16_smt:04x}", hk),
                "res": "",
            }

        emit_gpc(g2, e2)

        # ---------------- op+3: SUM + SRSH + STORE + LOOP ----------------
        g3 = op_gpc + 3
        e3 = {}
        for core in [core_i, core_iT, core_one, core_acc, core_shr, core_loop] + xv_cores + t_cores:
            e3[core] = add_self_keep(core)

        # acc = sum(t0..t12)
        srcs = t_cores
        m_sum = self._add_mask(core_acc, srcs)
        e3[core_acc] = {
            "z": self._z32_word(z16_add),
            "y": f"{m_sum:08x}",
            "c": "acc=sum(t0..t12)",
            "rc": "t0..t12",
            "cmd": self._format_mnemonic("ADD", f"{z16_add:04x}", m_sum),
            "res": "",
        }

        # shr = acc >> 31 ; and store to yo[i]
        # acc is left neighbor of shr => xx_left_xd=1
        z16_srsh_wr = self._make_z16("0a", write_en=True, xx_left_xd=True, a_bank_wr=True, a_addr_mode=1)
        e3[core_shr] = {
            "z": self._z32_word(z16_srsh_wr),
            "y": f"{31:08x}",
            "c": "yo[i]=(acc>>31) (A_WR)",
            "rc": "acc",
            "cmd": self._format_mnemonic("SRSH|A_WR", f"{z16_srsh_wr:04x}", 31),
            "res": "",
        }

        # loop: go back 4 GPCs (from next gpc) => offset = -4
        offset = (-4) & 0xFFFF
        y_loop = (1 << 31) | offset
        e3[core_loop] = {
            "z": self._z32_word(self._make_z16("00")),
            "y": f"{y_loop:08x}",
            "c": "loopen_1d=1, off=-4",
            "rc": "",
            "cmd": self._format_mnemonic("LOOP", "0000", y_loop),
            "res": "",
        }

        emit_gpc(g3, e3)

    # ---------------------------------------------------------------------
    # MIF emit
    # ---------------------------------------------------------------------
    def _add_line(self, addr, z_val, y_val, core, c_code, reg_comb, cmd, res_val, gpc):
        self.buffer_z[addr] = z_val
        self.buffer_y[addr] = y_val
        self.buffer_cmt[addr] = (
            f"{core:<6} {c_code:<30} {reg_comb:<30} {cmd:<20} {str(res_val):<8} GPC={gpc}"
        )

    def _write_mif_file(self, path, data_dict, cmt_dict, desc, header):
        max_addr = max(data_dict.keys()) if data_dict else -1
        if max_addr < 0:
            max_addr = 127
        end_addr = ((max_addr // 128) + 1) * 128 - 1
        end_addr = min(end_addr, self.mif_depth - 1)

        with open(path, "w", encoding="utf-8") as f:
            if header:
                f.write(f"{header}\n")

            f.write(f"-- {desc}\n")
            f.write(f"DEPTH = {self.mif_depth};\n")
            f.write("WIDTH = 32;\n")
            f.write("ADDRESS_RADIX = DEC;\n")
            f.write("DATA_RADIX = HEX;\n")
            f.write("CONTENT\nBEGIN\n")

            for addr in range(end_addr + 1):
                if addr % 128 == 0:
                    f.write(f"\n-- -- GPC {addr // 128} --\n")
                val = data_dict.get(addr, "00000000")
                cmt = cmt_dict.get(
                    addr,
                    f".r{addr%128:<4} {'':<30} {'':<30} {'':<20} 0        GPC={addr//128}",
                )
                f.write(f"{addr:<6} : {val}; -- {cmt}\n")
            f.write("END;\n")
